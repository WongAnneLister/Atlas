"""Read each dataset card's license and write `docs/LICENSES.md`.

One of only two modules that touch the network (the other is `download.py`).
Run with `make data-licenses`. The classifier never guesses: anything it does not
know, or any source flagged as third-party text, is "unclear" and ships scripts only.
"""

from __future__ import annotations

import argparse
import logging
from collections.abc import Callable
from datetime import UTC, datetime
from enum import StrEnum
from pathlib import Path
from typing import Any

from pydantic import BaseModel

from support_agent.config import REPO_ROOT, DataSource, get_settings

log = logging.getLogger(__name__)

LICENSES_PATH = REPO_ROOT / "docs" / "LICENSES.md"

# repo_id, revision -> card metadata dict (the YAML header of README.md)
CardFetcher = Callable[[str, str], dict[str, Any]]


class Redistribute(StrEnum):
    YES = "yes"
    NO = "no"
    UNCLEAR = "unclear"


# Lower-case HF license ids. Anything not listed here is "unclear".
_PERMISSIVE = {
    "mit",
    "apache-2.0",
    "bsd-2-clause",
    "bsd-3-clause",
    "cc0-1.0",
    "cc-by-3.0",
    "cc-by-4.0",
    "cdla-permissive-1.0",
    "cdla-permissive-2.0",
    "odc-by",
    "pddl",
    "unlicense",
}
_SHARE_ALIKE = {"cc-by-sa-3.0", "cc-by-sa-4.0", "cdla-sharing-1.0", "odbl"}
_PREFIX_NO = ("cc-by-nc", "cc-by-nd")  # non-commercial / no-derivatives clash with an MIT repo


class LicenseVerdict(BaseModel):
    name: str
    repo_id: str
    revision: str
    license_id: str | None
    redistribute: Redistribute
    action: str
    reason: str

    @property
    def link(self) -> str:
        return f"https://huggingface.co/datasets/{self.repo_id}/tree/{self.revision}"


def _normalise(raw: object) -> str | None:
    if isinstance(raw, list):
        # Several licenses: only safe to classify if there is exactly one.
        return _normalise(raw[0]) if len(raw) == 1 else None
    if not isinstance(raw, str) or not raw.strip():
        return None
    return raw.strip().lower()


def classify(source: DataSource, card: dict[str, Any]) -> LicenseVerdict:
    """Map card metadata to a redistribution verdict. Unknown means unclear."""
    license_id = _normalise(card.get("license"))
    raw_list = card.get("license")
    if isinstance(raw_list, list) and len(raw_list) > 1:
        verdict, reason = Redistribute.UNCLEAR, f"Card lists several licenses: {raw_list}."
    elif license_id is None:
        verdict, reason = Redistribute.UNCLEAR, "Card has no license field."
    elif license_id in {"other", "unknown"}:
        verdict, reason = Redistribute.UNCLEAR, f"Card license is '{license_id}'."
    elif license_id.startswith(_PREFIX_NO):
        verdict = Redistribute.NO
        reason = f"{license_id} forbids commercial use or derivatives; clashes with this MIT repo."
    elif license_id in _SHARE_ALIKE:
        verdict = Redistribute.YES
        reason = f"{license_id} allows sharing if derived data keeps its license and attribution."
    elif license_id in _PERMISSIVE:
        verdict, reason = Redistribute.YES, f"{license_id} is permissive (attribution only)."
    else:
        verdict, reason = Redistribute.UNCLEAR, f"License '{license_id}' is not in the known list."

    if source.third_party_note and verdict is not Redistribute.NO:
        verdict = Redistribute.UNCLEAR
        reason = f"Card says {license_id or 'nothing'}, but: {source.third_party_note.strip()}"

    action = {
        Redistribute.YES: "May commit processed text (keep license + attribution).",
        Redistribute.NO: "Scripts only. Never commit raw or processed text.",
        Redistribute.UNCLEAR: "Scripts only. Never commit raw or processed text.",
    }[verdict]
    return LicenseVerdict(
        name=source.name,
        repo_id=source.repo_id,
        revision=source.revision,
        license_id=license_id,
        redistribute=verdict,
        action=action,
        reason=reason,
    )


def hf_card(repo_id: str, revision: str) -> dict[str, Any]:
    """Fetch the card metadata (README.md YAML header) at a pinned revision."""
    from huggingface_hub import DatasetCard, hf_hub_download
    from huggingface_hub.errors import EntryNotFoundError

    try:
        path = hf_hub_download(repo_id, "README.md", repo_type="dataset", revision=revision)
    except EntryNotFoundError:
        return {}  # no card at all -> classified as "unclear"
    card = DatasetCard(Path(path).read_text(encoding="utf-8"))
    data: dict[str, Any] = card.data.to_dict()  # type: ignore[no-untyped-call]
    return data


def render(verdicts: list[LicenseVerdict], today: str) -> str:
    lines = [
        "# Dataset licenses",
        "",
        f"Generated by `make data-licenses` on {today} from each dataset card at its pinned",
        "revision (`configs/default.yaml` → `data.sources`). Do not edit by hand.",
        "",
        "Rule (AGENTS.md §5.3): only data marked **yes** may have processed text committed.",
        "A missing, unknown or third-party license is **unclear** and ships scripts only.",
        "",
        "| Dataset | License id | Redistribute processed text? | What we do |",
        "|---|---|---|---|",
    ]
    for v in verdicts:
        lines.append(
            f"| [{v.repo_id}]({v.link}) | `{v.license_id or 'missing'}` "
            f"| **{v.redistribute.value}** | {v.action} |"
        )
    lines += ["", "## Reasons", ""]
    lines += [f"- **{v.name}** (`{v.repo_id}`): {v.reason}" for v in verdicts]
    lines += [
        "",
        "Raw files always stay in `data/raw/` (gitignored), whatever the verdict.",
        "",
    ]
    return "\n".join(lines)


def build_report(sources: list[DataSource], fetch: CardFetcher = hf_card) -> list[LicenseVerdict]:
    return [classify(s, fetch(s.repo_id, s.revision)) for s in sources]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=LICENSES_PATH)
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    logging.getLogger("httpx").setLevel(logging.WARNING)

    from huggingface_hub.errors import HfHubHTTPError, LocalEntryNotFoundError

    try:
        verdicts = build_report(get_settings().data.sources)
    except (OSError, HfHubHTTPError, LocalEntryNotFoundError) as exc:
        log.error("cannot read dataset cards from the Hugging Face Hub: %s", exc)
        return 1
    today = datetime.now(UTC).date().isoformat()
    args.out.write_text(render(verdicts, today), encoding="utf-8")
    for v in verdicts:
        log.info("%s: %s -> %s", v.name, v.license_id, v.redistribute.value)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
