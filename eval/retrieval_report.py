"""Generate comparison tables and metadata-only rank CSVs from measured records."""

from __future__ import annotations

import csv
import io
import json
from collections import Counter
from collections.abc import Sequence
from pathlib import Path
from statistics import mean

from eval.common import FILTER_VARIANT_PREFIX
from eval.metrics import hit_all_at_k, mrr, recall_at_k
from eval.retrieval_records import RetrievalReportRun, RetrievalRun, SearchRecord, SearchReportRow
from support_agent.data.doc_models import write_text


def summary(
    records: Sequence[SearchRecord | SearchReportRow], ks: list[int]
) -> dict[str, float | int | None]:
    cross = [record for record in records if record.item.group == "cross_doc"]
    cutoff = max(ks)
    values: dict[str, float | int | None] = {"n": len(records)}
    for k in ks:
        values[f"Recall@{k}"] = mean(
            recall_at_k([c.section_id for c in r.chunks], r.item.gold_sections, k) for r in records
        )
    values[f"MRR@{cutoff}"] = mean(
        mrr([c.section_id for c in r.chunks[:cutoff]], r.item.gold_sections) for r in records
    )
    values[f"cross_doc hit_all@{cutoff}"] = (
        mean(
            hit_all_at_k([c.section_id for c in r.chunks], r.item.gold_sections, cutoff)
            for r in cross
        )
        if cross
        else None
    )
    values["mean latency (s)"] = mean(r.latency_s for r in records)
    return values


def table(records: Sequence[SearchRecord | SearchReportRow], ks: list[int], *, groups: bool) -> str:
    cutoff = max(ks)
    columns = [
        "n",
        *[f"Recall@{k}" for k in ks],
        f"MRR@{cutoff}",
        f"cross_doc hit_all@{cutoff}",
        "mean latency (s)",
    ]
    lines = ["| Mode | Group | " + " | ".join(columns) + " |", "|---|---|" + "---:|" * len(columns)]
    for mode in dict.fromkeys(r.mode for r in records):
        selected = [r for r in records if r.mode == mode]
        names = ["overall", *sorted({r.item.group for r in selected})] if groups else ["overall"]
        for group in names:
            rows = (
                selected if group == "overall" else [r for r in selected if r.item.group == group]
            )
            values = summary(rows, ks)
            cells = [
                "—"
                if values[key] is None
                else str(values[key])
                if key == "n"
                else f"{values[key]:.4f}"
                for key in columns
            ]
            lines.append(f"| {mode} | {group} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def failure_patterns(records: Sequence[SearchRecord | SearchReportRow], cutoff: int) -> list[str]:
    candidates = {(r.item.id, r.mode): r for r in records}
    patterns: Counter[str] = Counter()
    examples: dict[str, str] = {}
    for record in records:
        if record.item.split != "dev" or record.mode != "hybrid_rerank":
            continue
        gold = set(record.item.gold_sections)
        top = [c.section_id for c in record.chunks[:cutoff]]
        if gold.issubset(top):
            continue
        if record.item.group == "cross_doc" and gold.intersection(top):
            pattern = "Cross-document questions recover only part of the required evidence"
        elif record.item.group == "model_number" and top and top[0] not in gold:
            pattern = "A different product outranks the requested look-alike model"
        elif top and all(
            len(sid.split(".")) > 1
            and len(top[0].split(".")) > 1
            and sid.split(".")[1] != top[0].split(".")[1]
            for sid in gold
        ):
            pattern = "The leading result comes from another source/store scope"
        else:
            base = candidates.get((record.item.id, "hybrid"))
            available = {c.section_id for c in base.chunks} if base else set()
            pattern = (
                "Gold sections are absent from the fused candidate list"
                if gold - available
                else "Gold candidates fall below the rerank cutoff"
            )
        patterns[pattern] += 1
        examples.setdefault(pattern, record.item.id)
    return [
        f"- {name}: {count} dev misses; example `{examples[name]}`."
        for name, count in patterns.most_common(3)
    ] or ["- No dev misses observed."]


def write_reports(run: RetrievalRun | RetrievalReportRun, folder: Path, guide_path: Path) -> None:
    if not run.records or any(not r.item.answerable for r in run.records):
        raise ValueError("Reports require nonempty answerable-only records")
    meta = run.metadata
    ks = meta.settings["retrieval_eval"]["metric_ks"]
    cutoff = max(ks)
    splits = list(dict.fromkeys(r.item.split for r in run.records))
    filter_modes = list(
        dict.fromkeys(
            record.mode for record in run.records if record.mode.startswith(FILTER_VARIANT_PREFIX)
        )
    )
    header = [
        "# Retrieval comparison",
        "",
        "Generated by `make eval-retrieval`. Do not edit by hand.",
        "",
        f"- Git SHA (base revision): `{meta.git_sha}`",
        f"- Code hash: `{meta.code_hash}`",
        f"- Config hash: `{meta.config_hash}`",
        f"- Eval file hash: `{meta.eval_file_hash}`",
        f"- Frozen set hash: `{meta.frozen_set_hash}`",
        f"- Corpus hash: `{meta.corpus_hash}`",
        f"- Date (UTC): {meta.date}",
        f"- Requested split: {run.requested_split}; included: {', '.join(splits)}.",
        f"- Models: {json.dumps(meta.models, sort_keys=True)}",
        f"- Index identities: {json.dumps(meta.index_identities, sort_keys=True)}",
        "- Experiment collections: "
        + json.dumps(
            {
                "baseline": meta.settings["retrieval_eval"]["baseline_collection"],
                "heading_off": meta.settings["retrieval_eval"]["heading_ablation_collection"],
            },
            sort_keys=True,
        ),
        f"- Variant config hashes: {json.dumps(meta.variant_config_hashes, sort_keys=True)}",
        f"- Runtime packages: {json.dumps(meta.runtime, sort_keys=True)}",
        f"- Local verified chunk text: {meta.settings['retrieval_eval']['local_chunk_text']}.",
        "- Execution: embedding device `"
        + meta.settings["retrieval"]["embedding_device"]
        + "`; reranker device `"
        + meta.settings["retrieval"]["reranker_device"]
        + "`; reranker batch size "
        + str(meta.settings["retrieval"]["reranker_batch_size"])
        + "; reranker token limit "
        + str(meta.settings["retrieval"]["reranker_max_tokens"])
        + ".",
        f"- Review status: {meta.reviewed}/{meta.total_items} reviewed; "
        + (
            "unreviewed draft benchmark." if meta.reviewed < meta.total_items else "human reviewed."
        ),
        "- Dataset versions: " + json.dumps(meta.dataset_versions, sort_keys=True),
        "",
        "## Definitions and limitations",
        "",
        "Recall@k is the fraction of unique gold sections recovered in the first k chunks.",
        "Duplicate section chunks consume slots; they never increase recall twice.",
        f"MRR@{cutoff} uses the first relevant chunk, truncated identically for every mode.",
        "Cross-document hit_all requires every gold section; its denominator is cross_doc items.",
        "Latency sums original sequential component times, excluding model load and index build.",
        "With local_chunk_text enabled, ranked ids/scores hydrate from verified local text.",
        "Snapshot loading is excluded from query latency; these are warm-process timings.",
        "Cache hits retain original times; cache lookup speed is never reported as inference.",
        "Heading ablation reuses baseline BM25; normaliser ablation reuses baseline dense search.",
        "The configured token limit truncates long manuals and may remove useful evidence.",
        "Index fingerprints bind chunk text, model settings, index settings and runtime.",
        "The demo index is preserved; the configured baseline is a separately verified copy.",
        "Ablations compare hybrid with heading prefixes disabled in a separately re-embedded index",
        "and hybrid with model-number normalisation disabled. No test-set tuning was performed.",
        "CSV files export ids, ranks and metrics only; source questions/text stay in local caches.",
        "",
    ]
    tables: list[str] = []
    for split in splits:
        rows = [r for r in run.records if r.item.split == split]
        tables += [f"## {split}", "", table(rows, ks, groups=True), ""]
    if filter_modes:
        tables += [
            "## Metadata filter ablation",
            "",
            "These modes use the same corpus, hybrid search and reranker. Date filters use the",
            "configured current date. The category mode adds a category when exactly one is",
            "detected. Both searches must apply the filters for a row to count as applied.",
            "Older collections can be read without metadata filters.",
            "",
            "| Split | Mode | Filters applied |",
            "|---|---|---:|",
        ]
        for split in splits:
            for mode in filter_modes:
                rows = [r for r in run.records if r.item.split == split and r.mode == mode]
                if rows:
                    applied = sum(row.filters_applied for row in rows)
                    tables.append(f"| {split} | {mode} | {applied}/{len(rows)} |")
        tables.append("")
    test = [r for r in run.records if r.item.split == "test" and r.mode == "hybrid_rerank"]
    target = meta.settings["retrieval_eval"]["target_recall_at_5"]
    passed = bool(test) and summary(test, ks)["Recall@5"] >= target
    outcome = (
        f"Hybrid + rerank test Recall@5 {'meets' if passed else 'misses'} "
        f"the configured {target:.0%} target; results are reported unchanged."
        if test
        else "Only dev results are included; test is still required for final quality claims."
    )
    meaning = [
        "## What this means",
        "",
        "Recall measures gold-section coverage; MRR measures the first useful result.",
        outcome,
        "No-answer items are excluded; this experiment does not establish answer safety.",
        "",
    ]
    patterns = failure_patterns(run.records, cutoff)
    report = "\n".join(
        header + tables + meaning + ["## Top dev failure patterns", "", *patterns, ""]
    )
    write_text(folder / "retrieval.md", report)
    selections = [*splits, "all"] if run.requested_split == "all" else splits
    for split in selections:
        stream = io.StringIO()
        fields = [
            "id",
            "group",
            "split",
            "mode",
            "gold_sections",
            "ranked_section_ids",
            "ranked_chunk_ids",
            *[f"recall@{k}" for k in ks],
            f"mrr@{cutoff}",
            f"hit_all@{cutoff}",
            "latency_s",
            "cache_hit",
        ]
        if filter_modes:
            fields.extend(("filters", "filters_applied"))
        writer = csv.DictWriter(stream, fieldnames=fields, lineterminator="\n")
        writer.writeheader()
        for record in run.records:
            if split != "all" and record.item.split != split:
                continue
            sections = [c.section_id for c in record.chunks[:cutoff]]
            row = {
                "id": record.item.id,
                "group": record.item.group,
                "split": record.item.split,
                "mode": record.mode,
                "gold_sections": json.dumps(record.item.gold_sections),
                "ranked_section_ids": json.dumps(sections),
                "ranked_chunk_ids": json.dumps([c.chunk_id for c in record.chunks[:cutoff]]),
                f"mrr@{cutoff}": mrr(sections, record.item.gold_sections),
                f"hit_all@{cutoff}": hit_all_at_k(sections, record.item.gold_sections, cutoff),
                "latency_s": record.latency_s,
                "cache_hit": record.cache_hit,
            }
            if filter_modes:
                row["filters"] = record.filters.model_dump_json() if record.filters else ""
                row["filters_applied"] = record.filters_applied
            row.update(
                {f"recall@{k}": recall_at_k(sections, record.item.gold_sections, k) for k in ks}
            )
            writer.writerow(row)
        write_text(folder / f"retrieval_{split}.csv", stream.getvalue())
    guide = guide_path.read_text(encoding="utf-8") if guide_path.exists() else "# Retrieval\n"
    before, marker, measured = guide.partition("## Measured ingestion")
    before = before.split("## Retrieval experiment", 1)[0].rstrip()
    selected = [r for r in run.records if r.item.split == ("test" if test else "dev")]
    section = "\n".join(
        [
            "## Retrieval experiment",
            "",
            "Source: eval/reports/retrieval.md",
            "",
            table(selected, ks, groups=False),
            "",
            *meaning,
            "## Dev failure patterns",
            "",
            *patterns,
            "",
            "These draft-set results are not evidence of safe answer acceptance.",
            "",
        ]
    )
    write_text(guide_path, before + "\n\n" + section + "\n" + marker + measured)
