"""Produce the complete round-two comparison and its bar chart from saved measurements."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from eval.common import load_items
from eval.coverage_compare import paired_lines
from eval.coverage_eval import CoverageRecord, load_complete_run
from eval.e2e_records import E2EMetadata, E2ERecord
from eval.metrics import outcome_rates
from support_agent.config import REPO_ROOT
from support_agent.data.doc_models import digest, write_text


def coverage_run(path: Path) -> tuple[dict, list[CoverageRecord]]:
    return load_complete_run(path, REPO_ROOT / "eval/runs/coverage-round2-inputs.jsonl")


def load_run(path: Path) -> tuple[E2EMetadata, dict[str, E2ERecord]]:
    """Reject duplicate full-graph records before indexing them by id."""
    lines = path.read_text().splitlines()
    meta = E2EMetadata.model_validate_json(lines[0])
    rows = [E2ERecord.model_validate_json(line) for line in lines[1:] if line.strip()]
    indexed = {r.item.id: r for r in rows}
    if len(indexed) != len(rows):
        raise ValueError("Full-graph summary contains duplicate items")
    return meta, indexed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--baseline", type=Path, default=Path("eval/runs/routing-round1-test.jsonl")
    )
    parser.add_argument(
        "--candidate", type=Path, default=Path("eval/runs/coverage-round2-test.jsonl")
    )
    args = parser.parse_args(argv)
    manifest_path = REPO_ROOT / "eval/reports/coverage_round2_manifest.json"
    manifest = json.loads(manifest_path.read_text())
    for path, expected in manifest["production_files"].items():
        if hashlib.sha256((REPO_ROOT / path).read_bytes()).hexdigest() != expected:
            raise ValueError(f"Candidate production file changed after freeze: {path}")
    a_meta, before = load_run(REPO_ROOT / args.baseline)
    b_meta, after = load_run(REPO_ROOT / args.candidate)
    for key in (
        "config_hash",
        "eval_file_hash",
        "corpus_hash",
        "models",
        "dataset_versions",
        "split",
        "customer_id",
        "threshold",
    ):
        if getattr(a_meta, key) != getattr(b_meta, key):
            raise ValueError(f"Full-graph comparison changed {key}")
    eval_path = REPO_ROOT / "eval/sets/eval_v1.jsonl"
    if b_meta.eval_file_hash != digest(eval_path.read_text()):
        raise ValueError("Full-graph frozen evaluation file changed")
    expected = {i.id: i.model_dump() for i in load_items(eval_path) if i.split == "test"}
    if {k: r.item.model_dump() for k, r in after.items()} != expected:
        raise ValueError("Full-graph summary requires complete identical frozen inputs")
    if len(before) != 150 or len(after) != 150:
        raise ValueError("Need both complete full-test runs")
    if {k: r.item.model_dump() for k, r in before.items()} != {
        k: r.item.model_dump() for k, r in after.items()
    }:
        raise ValueError("Full-graph frozen questions or labels changed")
    lines = [
        "# Evidence coverage round two: measured summary",
        "",
        "Generated by `make eval-coverage-summary`; metrics come from the saved runs.",
        "",
        "Full provenance is in the linked reports and pre-test production manifest.",
        "",
        "## Answer-stage controls and dev",
        "",
        "| Split / subset | Original accepted / total | Candidate accepted / total | "
        "Original false accept | Candidate false accept | Original reject | Candidate reject |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for split, old_path, new_path in (
        (
            "dev",
            "eval/runs/coverage-round2-before-dev-network.jsonl",
            "eval/runs/coverage-round2-after-dev.jsonl",
        ),
        (
            "control test",
            "eval/runs/coverage-round2-before-controls-test.jsonl",
            "eval/runs/coverage-round2-after-controls-test.jsonl",
        ),
    ):
        _, old = coverage_run(REPO_ROOT / old_path)
        new_meta, new = coverage_run(REPO_ROOT / new_path)
        paired_lines(new_meta, new, REPO_ROOT / old_path)
        for subset in sorted({r.case.subset for r in new}):
            selected = [[r for r in rows if r.case.subset == subset] for rows in (old, new)]
            rates = [
                outcome_rates([r.case.complete for r in rows], [r.accepted for r in rows])
                for rows in selected
            ]
            accepts = [
                f"{rate.accepted_count}/{len(rows)}"
                for rate, rows in zip(rates, selected, strict=True)
            ]
            fa = [
                f"{rate.false_accept:.2%}" if any(not r.case.complete for r in rows) else "n/a"
                for rate, rows in zip(rates, selected, strict=True)
            ]
            fr = [
                f"{rate.false_reject:.2%}" if any(r.case.complete for r in rows) else "n/a"
                for rate, rows in zip(rates, selected, strict=True)
            ]
            lines.append(
                f"| {split} / {subset} | {accepts[0]} | {accepts[1]} | "
                f"{fa[0]} | {fa[1]} | {fr[0]} | {fr[1]} |"
            )
    lines += [
        "",
        "## Complete full-test regression",
        "",
        f"- Original collection: `{a_meta.git_sha}`, {a_meta.date}",
        f"- Candidate collection: `{b_meta.git_sha}`, {b_meta.date}",
        f"- Same config: `{b_meta.config_hash}`",
        f"- Same frozen evaluation: `{b_meta.eval_file_hash}`",
        f"- Same models: `{b_meta.models}`",
        "",
        "| Outcome | Routing round one | Coverage round two |",
        "|---|---:|---:|",
    ]
    rates = [
        outcome_rates(
            [r.item.answerable for r in rows.values()], [r.accepted for r in rows.values()]
        )
        for rows in (before, after)
    ]
    for label, key in (
        ("No-answer false accept", "false_accept"),
        ("Answerable false reject", "false_reject"),
        ("Accepted outcomes", "pass_rate"),
    ):
        lines.append(f"| {label} | {getattr(rates[0], key):.2%} | {getattr(rates[1], key):.2%} |")
    lines += [
        "",
        "## Limits",
        "",
        "The old full test is a regression set already observed before this round.",
        "Control test topics were reserved before inference; labels are authored and unreviewed.",
        "Original dev gold describes corpus answerability, not complete context coverage.",
        "Accepted outcomes are not human-confirmed answer accuracy.",
        "Quote membership does not prove entailment or complete question decomposition.",
        "All dependency failures remain in the measured outcome denominators.",
        "A zero observed false-accept rate on this small set is not a production guarantee.",
        "",
        "Reports: `coverage_round2_dev.md`, `coverage_round2_controls_test.md`, "
        "`coverage_round2_test.md`, `coverage_round2_compare.md`.",
        "",
    ]
    write_text(REPO_ROOT / "eval/reports/coverage_round2_summary.md", "\n".join(lines))
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    labels = ["No-answer false accept", "Answerable false reject"]
    x = list(range(len(labels)))
    fig, ax = plt.subplots(figsize=(8, 4.5))
    for offset, rate, name, color in (
        (-0.18, rates[0], "Routing round one", "#64748b"),
        (0.18, rates[1], "Coverage round two", "#0f766e"),
    ):
        values = [rate.false_accept * 100, rate.false_reject * 100]
        bars = ax.bar([v + offset for v in x], values, width=0.34, label=name, color=color)
        ax.bar_label(bars, labels=[f"{v:.2f}%" for v in values], padding=4)
    ax.set_xticks(x, labels)
    ax.set_ylim(0, max(15, max(r.false_reject * 100 for r in rates) + 8))
    ax.set_ylabel("Percent (lower is better)")
    ax.set_title("Full-test regression: safety and rejection trade-off")
    ax.legend(loc="upper left")
    fig.text(
        0.5,
        0.01,
        "Same 150 draft questions; acceptance is not answer accuracy.",
        ha="center",
        fontsize=9,
    )
    fig.tight_layout(rect=(0, 0.035, 1, 1))
    fig.savefig(REPO_ROOT / "eval/reports/coverage_round2.png", dpi=160)
    plt.close(fig)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
