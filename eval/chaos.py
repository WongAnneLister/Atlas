"""Run the frozen test smoke set with seeded dependency fault injection."""

import argparse
import json
import sys
from pathlib import Path

import yaml
from pydantic import ValidationError

from eval import e2e_eval
from eval.e2e_runs import HANDOFF_METRIC_PREFIX, RELIABILITY_METRICS
from eval.run_record import RUNS, Run, RunManifest, RunMetrics, confidence_level, format_summary
from support_agent.config import REPO_ROOT, Settings, get_settings
from support_agent.data.doc_models import write_text
from support_agent.reliability.settings import ChaosSettings

DEFAULT_CONFIG = Path("configs/chaos.yaml")
DEFAULT_REPORT = Path("eval/reports/chaos.md")


def load_settings(path: Path) -> Settings:
    document = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(document, dict) or set(document) != {"chaos"}:
        raise ValueError("Chaos overlay must contain only a chaos settings mapping")
    overlay = document["chaos"]
    if not isinstance(overlay, dict) or set(overlay).difference(ChaosSettings.model_fields):
        raise ValueError("Chaos overlay contains invalid settings")
    if overlay.get("enabled") is not True:
        raise ValueError("Chaos overlay must explicitly enable fault injection")
    effective = get_settings().chaos.model_dump() | overlay
    return Settings(chaos=ChaosSettings.model_validate(effective))


def render_chaos(manifest: RunManifest, metrics: RunMetrics, path: Path) -> int:
    dataset = manifest.datasets.get("smoke")
    if manifest.kind != "chaos" or manifest.split != "test" or not (dataset and dataset.version):
        raise ValueError("Expected a chaos run on the versioned test smoke set")
    settings = ChaosSettings.model_validate(manifest.source.get("chaos"))
    false_accepts = metrics.metrics["false_accept"]
    if false_accepts.count is None:
        raise ValueError("Chaos run is missing a binary no-answer outcome")
    failed = false_accepts.count > 0
    handoffs = [
        (name.removeprefix(HANDOFF_METRIC_PREFIX), summary.count)
        for name, summary in sorted(metrics.metrics.items())
        if name.startswith(HANDOFF_METRIC_PREFIX)
    ]
    lines = [
        "# Chaos evaluation",
        "",
        "Generated by `make chaos` using the frozen test smoke set.",
        "",
        f"- Git SHA: `{manifest.git_sha}`",
        f"- Working tree changed at collection: {manifest.dirty}",
        f"- Config hash: `{manifest.config_hash}`",
        f"- Dataset: smoke {dataset.version} (`{dataset.sha256}`)",
        f"- Source datasets: {json.dumps(manifest.source.get('dataset_versions'), sort_keys=True)}",
        f"- Split: {manifest.split}",
        f"- Date (UTC): {manifest.started_at.isoformat() if manifest.started_at else 'unknown'}",
        f"- Models: {json.dumps(manifest.models, sort_keys=True)}",
        f"- LLM endpoint host: {manifest.source.get('endpoint_host') or 'unknown'}",
        f"- Fault settings: {json.dumps(settings.model_dump(), sort_keys=True)}",
        "",
        f"| Metric | Estimate and {confidence_level(metrics):.0%} CI |",
        "|---|---|",
        f"| Answer rate | {format_summary(metrics.metrics['pass_rate'])} |",
        f"| No-answer false accepts | {format_summary(false_accepts)} |",
        "",
        (
            "The run accepted a no-answer item. This is a release blocker."
            if failed
            else "The run observed zero no-answer false accepts."
        ),
        "",
        "Fallback counts include each call that tried an alternate model.",
        "",
        "| Reliability events | Total | Events per turn and CI |",
        "|---|---:|---|",
    ]
    for name in RELIABILITY_METRICS:
        summary = metrics.metrics[name]
        total = round(summary.interval.point * summary.n)
        lines.append(f"| {name.title()} | {total} | {format_summary(summary, rate=False)} |")
    lines += [
        "",
        "| Handoff reason | Turns |",
        "|---|---:|",
        *([f"| {reason} | {count} |" for reason, count in handoffs] or ["| None observed | 0 |"]),
    ]
    write_text(path, "\n".join(lines) + "\n")
    return int(failed)


def _render_run(run: Run, path: Path) -> int:
    return render_chaos(run.manifest, run.metrics, path)


def main(argv: list[str] | None = None) -> int:
    arguments = argv if argv is not None else sys.argv[1:]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=DEFAULT_CONFIG)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    parser.add_argument("--eval-file", type=Path, default=Path("eval/sets/smoke.jsonl"))
    parser.add_argument("--run-root", type=Path, default=RUNS)
    parser.add_argument("--run-suffix")
    parser.add_argument("--run-pointer", type=Path)
    parser.add_argument(
        "--run-dir", type=Path, help="render saved aggregate results without models"
    )
    args = parser.parse_args(arguments)
    if args.run_dir:
        directory = REPO_ROOT / args.run_dir
        manifest = RunManifest.model_validate_json((directory / "manifest.json").read_bytes())
        metrics = RunMetrics.model_validate_json((directory / "metrics.json").read_bytes())
        return render_chaos(manifest, metrics, REPO_ROOT / args.report)

    try:
        settings = load_settings(REPO_ROOT / args.config)
    except ValidationError as error:
        messages = error.errors(include_input=False, include_context=False, include_url=False)
        parser.error("\n".join(detail["msg"] for detail in messages))
    except yaml.YAMLError:
        parser.error("Chaos configuration must be valid YAML")
    except (OSError, ValueError) as error:
        parser.error(str(error))
    forwarded = [
        "--split",
        "test",
        "--eval-file",
        str(args.eval_file),
        "--expect-dataset",
        "smoke",
        "--fresh",
        "--report",
        str(args.report),
        "--run-root",
        str(args.run_root.resolve()),
    ]
    if args.run_suffix:
        forwarded.extend(["--run-suffix", args.run_suffix])
    if args.run_pointer:
        forwarded.extend(["--run-pointer", str(args.run_pointer)])
    return e2e_eval.main(
        forwarded,
        chaos_settings=settings,
        renderer=_render_run,
        collection_command=["python", "-m", "eval.chaos", *arguments],
    )


if __name__ == "__main__":
    raise SystemExit(main())
