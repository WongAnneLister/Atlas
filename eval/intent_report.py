"""Intent and path metrics with metadata-only reporting."""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path
from statistics import mean
from typing import Any

from eval.intent_records import IntentRecord, IntentRun
from support_agent.data.doc_models import write_text
from support_agent.graph.intents import INTENT_TO_PATH, Intent


def confusion_matrix(records: list[IntentRecord]) -> tuple[list[str], list[list[int]]]:
    labels = [intent.value for intent in Intent]
    matrix = [[0 for _ in labels] for _ in labels]
    for record in records:
        matrix[labels.index(record.item.intent.value)][labels.index(record.predicted.value)] += 1
    return labels, matrix


def intent_metrics(records: list[IntentRecord]) -> dict[str, Any]:
    if not records:
        raise ValueError("Intent metrics require nonempty predictions")
    per_intent = {}
    for intent in Intent:
        gold = sum(r.item.intent == intent for r in records)
        predicted = sum(r.predicted == intent for r in records)
        correct = sum(r.item.intent == r.predicted == intent for r in records)
        per_intent[intent] = {
            "support": gold,
            "predicted": predicted,
            "precision": correct / predicted if predicted else 0.0,
            "recall": correct / gold if gold else 0.0,
        }
    return {
        "n": len(records),
        "accuracy": mean(r.item.intent == r.predicted for r in records),
        "path_accuracy": mean(
            INTENT_TO_PATH[r.item.intent] == INTENT_TO_PATH[r.predicted] for r in records
        ),
        "macro_precision": mean(v["precision"] for v in per_intent.values()),
        "macro_recall": mean(v["recall"] for v in per_intent.values()),
        "failures": sum(r.parse_failed for r in records),
        "mean_latency_s": mean(r.latency_s for r in records),
        "per_intent": per_intent,
    }


def write_report(run: IntentRun, path: Path) -> None:
    meta, records = run.metadata, run.records
    values = intent_metrics(records)
    lines = [
        "# Intent classification",
        "",
        "Generated by `make eval-intent`; do not edit by hand.",
        "",
    ]
    for title, key in (
        ("Git SHA (base revision)", "git_sha"),
        ("Code hash", "code_hash"),
        ("Config hash", "config_hash"),
        ("Prompt hash", "prompt_hash"),
        ("Dataset hash", "dataset_hash"),
        ("Date (UTC)", "date"),
        ("Provider", "provider"),
        ("Model", "model"),
        ("Response model names", "response_models"),
        ("Model options", "model_options"),
        ("Dataset versions", "dataset_versions"),
        ("Input construction", "sample_stats"),
    ):
        lines.append(f"- {title}: `{json.dumps(meta[key], sort_keys=True)}`")
    if "runtime" in meta:
        lines.append(f"- Runtime: `{json.dumps(meta['runtime'], sort_keys=True)}`")
    if "input_hashes" in meta:
        lines.append(f"- Input hashes: `{json.dumps(meta['input_hashes'], sort_keys=True)}`")
    if "endpoint" in meta:
        lines.append(f"- Provider endpoint: `{meta['endpoint']}`")
    lines += [
        "- Eval split: intent_holdout; deterministic Bitext holdout plus "
        "separately sourced extras.",
        "- No fitting or tuning on this held-out result. "
        "Confidence is self-reported, not calibrated.",
        "- Inputs and mapped gold labels are unreviewed drafts; counts below are not human review.",
        "",
        "## Overall",
        "",
        "| Metric | Value |",
        "|---|---:|",
        f"| Questions | {values['n']} |",
        f"| Intent accuracy | {values['accuracy']:.4f} |",
        f"| Path accuracy | {values['path_accuracy']:.4f} |",
        f"| Macro precision | {values['macro_precision']:.4f} |",
        f"| Macro recall | {values['macro_recall']:.4f} |",
        f"| Parse/invocation failures | {values['failures']} |",
        f"| Mean original query latency (s) | {values['mean_latency_s']:.4f} |",
        "",
        "Intent accuracy requires the exact label; path accuracy requires the same workflow path.",
        "Failures use the graph's fixed-path fallback and remain in both accuracy denominators.",
        "Macro metrics weight each of the nine intents equally; "
        "unpredicted labels have zero precision.",
        "Latency excludes model initialization; cache hits preserve original inference times.",
        "",
        "## Per intent",
        "",
        "| Intent | Support | Predicted | Precision | Recall |",
        "|---|---:|---:|---:|---:|",
    ]
    for intent, row in values["per_intent"].items():
        lines.append(
            f"| {intent.value} | {row['support']} | {row['predicted']} | "
            f"{row['precision']:.4f} | {row['recall']:.4f} |"
        )
    labels, matrix = confusion_matrix(records)
    lines += [
        "",
        "## Confusion matrix",
        "",
        "Rows are gold intents; columns are predicted intents.",
        "",
        "| Gold / predicted | " + " | ".join(labels) + " |",
        "|---|" + "---:|" * len(labels),
    ]
    for label, row in zip(labels, matrix, strict=True):
        lines.append("| " + label + " | " + " | ".join(map(str, row)) + " |")
    counts = Counter(
        (r.item.intent.value, r.predicted.value) for r in records if r.item.intent != r.predicted
    )
    lines += ["", "## Confusions", "", "| Gold | Predicted | Count |", "|---|---|---:|"]
    for (gold, predicted), count in counts.most_common():
        lines.append(f"| {gold} | {predicted} | {count} |")
    if not counts:
        lines.append("| No intent errors | — | 0 |")
    lines += [
        "",
        "## Source coverage",
        "",
        "| Source label | Questions |",
        "|---|---:|",
    ]
    for source, count in sorted(Counter(r.item.source_label for r in records).items()):
        lines.append(f"| {source} | {count} |")
    target = meta["target_accuracy"]
    lines += [
        "",
        "## Interpretation and limits",
        "",
        f"Intent accuracy {'meets' if values['accuracy'] >= target else 'misses'} "
        f"the configured {target:.0%} target; results are unchanged.",
        "A correct path still may contain the wrong action; path accuracy is not task success.",
        "Product extras come only from retrieval dev questions, not its test split.",
        "Return extras were model-drafted; greetings were authored separately.",
        "The classifier and return drafter share a provider, limiting independence.",
        "Normalized exact duplicates are excluded; "
        "near-paraphrases can cross the Bitext partition.",
        "Source balancing changes the natural intent distribution, "
        "so accuracy is benchmark-specific.",
        "Mapped Bitext labels sometimes hide ambiguity "
        "between general rules and individual actions.",
        "Unsupported account/review requests use the fixed path "
        "under this project's declared scope.",
        "All five graph paths are stubs; "
        "this measures classification, not answers or refusal safety.",
        "The provider alias and response model names do not pin immutable model weights.",
        "",
    ]
    write_text(path, "\n".join(lines))
