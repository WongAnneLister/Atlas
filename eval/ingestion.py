"""Reproduce source chunk statistics and distinguish real index runs from chunk-only checks."""

from __future__ import annotations

import argparse
import subprocess
import xml.etree.ElementTree as ET
from collections import Counter
from datetime import UTC, datetime
from importlib.metadata import version
from statistics import mean

from support_agent.config import REPO_ROOT, get_settings
from support_agent.data.doc_models import digest, write_text
from support_agent.data.manifest import load_manifest
from support_agent.ingest import IngestRun
from support_agent.retrieval.chunking import Chunk


def main(*, preview: bool = False) -> None:
    settings = get_settings()
    output = REPO_ROOT / settings.data.processed_dir
    if preview:
        output /= settings.index.preview_directory
    run = IngestRun.model_validate_json((output / "ingest_run.json").read_text(encoding="utf-8"))
    text = (output / "chunks.jsonl").read_text(encoding="utf-8")
    chunks = [Chunk.model_validate_json(line) for line in text.splitlines() if line.strip()]
    if digest(text) != run.chunk_hash or len(chunks) != run.chunk_count:
        raise ValueError("Chunk artifact differs from recorded ingestion run")
    sha = subprocess.check_output(
        ["git", "-c", f"safe.directory={REPO_ROOT.as_posix()}", "rev-parse", "HEAD"],
        cwd=REPO_ROOT,
        text=True,
    ).strip()
    modules = sorted((REPO_ROOT / "src/support_agent/retrieval").glob("*.py"))
    code_hash = digest(
        "".join(path.name + digest(path.read_text(encoding="utf-8")) for path in modules)
    )
    counts = Counter(chunk.doc_id for chunk in chunks)
    products = [c for c in chunks if c.section_id.startswith("product.")]
    policies = [c for c in chunks if not c.section_id.startswith("product.")]
    integration = "not run"
    junit = output / "milvus_integration.xml"
    if junit.exists():
        cases = list(ET.parse(junit).iter("testcase"))
        passed = sum(
            not any(case.find(tag) is not None for tag in ("failure", "error", "skipped"))
            for case in cases
        )
        integration = f"{passed}/{len(cases)} passed (real-server test; fake vectors)"
    packages = ("FlagEmbedding", "transformers", "pymilvus")
    lines = [
        "# Chunking and ingestion report",
        "",
        "Generated by `make eval-ingest`. Do not edit by hand.",
        "",
        f"- Git SHA (base revision when run): `{sha}`",
        f"- Retrieval code hash: `{code_hash}`",
        f"- Config hash: `{run.config_hash}`",
        f"- Corpus hash: `{run.corpus_hash}`",
        f"- Chunk hash: `{run.chunk_hash}`",
        f"- Date (UTC): {datetime.now(UTC).date().isoformat()}",
        f"- Tokenizer/model: `{run.embedding_model}@{run.embedding_revision}`",
        f"- Reranker (not loaded): `{settings.retrieval.reranker_model}`",
        "- Runtime packages: " + ", ".join(f"{name} {version(name)}" for name in packages),
        "- Dataset version: processed docs from pinned raw sources listed below.",
        "- Eval split: not applicable; full-corpus ingestion integrity, no quality tuning.",
        "",
        "## Actual run status",
        "",
        f"- Status: `{run.status}`",
        f"- Milvus server: `{run.server_version or 'not connected'}`",
        f"- Stored rows: {run.stored_count if run.stored_count is not None else 'not measured'}",
        f"- Encoder windows evaluated: {run.embedding_windows}",
        f"- Manual integration test: {integration}",
        f"- Error: {run.error or 'none'}",
        "",
        "## Source chunk counts",
        "",
        "| Measure | Value |",
        "|---|---:|",
        f"| documents | {len(counts)} |",
        f"| sections | {len({c.section_id for c in chunks})} |",
        f"| chunks | {len(chunks)} |",
        f"| policy chunks | {len(policies)} |",
        f"| whole product chunks | {len(products)} |",
        f"| average body tokens | {mean(c.n_tokens for c in chunks):.2f} |",
        f"| maximum body tokens | {max(c.n_tokens for c in chunks)} |",
        f"| maximum policy body tokens | {max((c.n_tokens for c in policies), default=0)} |",
        f"| configured policy budget | {run.policy_max_tokens} |",
        f"| configured overlap | {run.policy_overlap_tokens} |",
        f"| configured encoder window including special tokens | {run.encoder_window_tokens} |",
        "",
        "| Document | Chunks |",
        "|---|---:|",
        *[f"| {doc} | {count} |" for doc, count in sorted(counts.items())],
        "",
        "## Timings",
        "",
        *[f"- {key}: {value:.3f} seconds" for key, value in run.timings_s.items()],
        "",
        "## Dataset revisions",
        "",
        *[
            f"- {name}: `{record.repo_id}@{record.revision}`"
            for name, record in sorted(
                load_manifest(REPO_ROOT / settings.data.raw_dir).sources.items()
            )
        ],
        "",
        "A chunk-only or failed run is not proof of real embedding or successful Milvus ingestion.",
        "The integration fixture checks database behavior; it does not measure BGE quality.",
        "",
    ]
    report = "\n".join(lines)
    if preview:
        write_text(output / "ingestion.md", report)
        return
    write_text(REPO_ROOT / "eval/reports/ingestion.md", report)
    guide_path = REPO_ROOT / "docs/RETRIEVAL.md"
    guide = guide_path.read_text(encoding="utf-8").split("## Measured ingestion", 1)[0]
    write_text(guide_path, guide.rstrip() + "\n\n## Measured ingestion\n\n" + report)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--preview", action="store_true")
    main(preview=parser.parse_args().preview)
