"""Reproduce the document validator report and build guide. Run make eval-docs."""

from __future__ import annotations

import subprocess
from datetime import UTC, datetime

from support_agent.config import REPO_ROOT, get_settings
from support_agent.data.build_docs import build_docs
from support_agent.data.doc_models import BuildIndex, digest, json_text, write_text
from support_agent.data.manifest import load_manifest
from support_agent.data.validate_docs import summary_table, validate_docs


def main() -> None:
    settings = get_settings()
    result = validate_docs(settings)
    processed = REPO_ROOT / settings.data.processed_dir
    before = {p.relative_to(processed): p.read_bytes() for p in processed.rglob("*") if p.is_file()}
    build_docs(settings)
    after = {p.relative_to(processed): p.read_bytes() for p in processed.rglob("*") if p.is_file()}
    if before != after:
        raise ValueError("Rebuild changed generated artifact bytes")
    index = BuildIndex.model_validate_json(
        (processed / "build_index.json").read_text(encoding="utf-8"),
    )
    sha = subprocess.check_output(
        ["git", "-c", f"safe.directory={REPO_ROOT.as_posix()}", "rev-parse", "HEAD"],
        cwd=REPO_ROOT,
        text=True,
    ).strip()
    modules = sorted((REPO_ROOT / "src/support_agent/data").glob("*.py"))
    code_hash = digest("".join(p.name + digest(p.read_text(encoding="utf-8")) for p in modules))
    lines = [
        "# Document build report",
        "",
        "Generated by `make eval-docs`. Do not edit by hand.",
        "",
        f"- Git SHA (base revision when run): `{sha}`",
        f"- Data build code hash: `{code_hash}`",
        f"- Config hash: `{index.config_hash}`",
        f"- Input hash: `{index.input_hash}`",
        f"- Run date (UTC): {datetime.now(UTC).date().isoformat()}",
        f"- Document built_at (latest input manifest date): {index.built_at}",
        "- Eval split: not applicable (full source document integrity check, no tuning).",
        "- Models: no rewriting model; see topic decision methods below.",
        f"- Topic models actually recorded in cache: `{index.topic_models}`",
        f"- Embedding model (not loaded): `{settings.retrieval.embedding_model}`",
        f"- Reranker model (not loaded): `{settings.retrieval.reranker_model}`",
        "",
        "## Dataset versions",
        "",
    ]
    manifest = load_manifest(REPO_ROOT / settings.data.raw_dir)
    lines.extend(
        f"- {name}: `{record.repo_id}@{record.revision}`"
        for name, record in sorted(manifest.sources.items())
    )
    lines += [
        "",
        "## Validator results",
        "",
        summary_table(result),
        "",
        f"Documents: {len(result.documents)}.",
        "Byte-identical rebuild: passed (all processed artifacts, including the topic cache).",
        "",
        "Coverage uses all raw FAQ rows, including duplicates and empty answers.",
        "A duplicate counts as covered only when its question and answer survive.",
        "Words count section bodies, including source question context, excluding headings.",
        "",
        "## Dedupe and topic audit",
        "",
        "```json",
        json_text(
            {
                "dedupe": result.dedupe_counts,
                "topic_methods": result.topic_methods,
                "excluded": result.excluded,
            }
        ).strip(),
        "```",
        "",
        "The audit counts merged groups, not a retrieval or answer-quality score.",
        "",
    ]
    report = "\n".join(lines)
    write_text(REPO_ROOT / "eval/reports/docs_build.md", report)
    guide = """# Document build

Generated by `make eval-docs`. Rebuild inputs with `make data-docs`.
Download pinned inputs first with `make data-download`.

## Topic rules

Question keywords take priority over source category keywords.
Ordered patterns and all thresholds live in `configs/default.yaml` under `data.docs`.
Leftovers use the fast model only when configured, through the shared LLM factory.
Otherwise they remain `other`, explicitly recorded as `other_without_model`.
The cache stores content and prompt hashes, topic, and decision method.
The same inputs, config and cache produce byte-identical build artifacts.
Delete `data/processed/topic_cache.jsonl` to reclassify leftovers after configuring a model.
`built_at` uses the latest input manifest date, never the wall clock.

## Dedupe and fact preservation

HTML tags and hidden scripts/styles are stripped; entities and whitespace are normalised.
Unicode is normalised with NFKC. Empty questions or answers are excluded and reported.
Exact duplicates use a hash of dataset, category, normalised question and answer.
Near duplicates require identical answers, identical question numbers, and similar questions.
Similarity uses Python's SequenceMatcher with the configured threshold.
Every source id and every distinct question remain in provenance and the rendered context.
Sections group answers by topic, source and original category, never across store scopes.
Stable section ids use the topic, source, readable category and full category hash.
Source answers are joined as prose with their question context; no LLM rewrites facts.
The validator reloads raw FAQs and requires each covered question and answer to survive.
It also rejects new numeric tokens or units, missing facts, bad provenance and duplicate ids.
Every section has a source mapping, even though no rewriting model is used.

## Synthetic policy versions

The version fixture invents historical rules for the generic store to test date selection.
The current sections keep their real wording and section IDs so frozen v1 labels still apply.
The synthetic history changes the returns window from 90 to 30 days and the price-adjustment
window from 14 to 7 days. Both changes take effect on 2026-09-01.
The historical interval runs from 2026-01-01 through 2026-08-31.
Its section ID ends in `@2026-01-01`, and its heading ends in ` (policy before 2026-09-01)`.

The source sentences and replacements live in `src/support_agent/data/policy_versions.yaml`.
The builder requires each source sentence to occur exactly once before it creates the copy.
`policy_versions.enabled` includes the historical sections in the default build. Validation
checks the synthetic copies against the version spec and preserves their source provenance.
Ordinary source checks still apply to the current sections.

## Section metadata

`make data-docs` writes `data/processed/docs/section_metadata.json` with a record for each
Markdown section ID. Policy sections use the FAQ topic and an empty product category. Catalog
sections use the `catalog` topic and the category assigned from the product model. All regions
are `global`.

The validity window includes `effective_from` and excludes `effective_to`. A null end is open.
Unversioned sections start on `policy_versions.default_effective_from` (2026-01-01 in the
default config). The version spec supplies both dates for historical sections and the start
date for their current sections.

Preview chunking and index builds require complete section metadata. Run `make data-docs`
to regenerate the sidecar before building an index from older documents. The index registry
stores the metadata alongside the heading. A date or other metadata edit changes the
section's content hash and triggers an update even when the prose and heading stay the same.

## Products and limits

Models come from PDF cover text. Filenames are not authoritative.
Each cover model gets a separate catalog row and section with its exact model code.
Descriptions retain the full extracted manual or leaflet text, including caveats.
Attributes retain explicit key:value lines; shared manuals leave attributes empty.
Shared monitor manual text remains shared evidence, not model-specific specifications.
Model-question diversity needs review in commit 05.
PDF text extraction loses table layout. Manual descriptions are long and need chunking in commit 06.
Store names, India-specific conditions and conflicting policies remain visible.
Off-topic categories are kept for coverage and marked by their original category.
They must not be presented as universal store policies by later retrieval and answer paths.
The numeric guard is a necessary check; it does not prove semantic equivalence for future rewrites.
Permitted prose extraction avoids that risk in this build.
All mixed processed output is gitignored under `docs/LICENSES.md`; only scripts and counts ship.
Bitext responses are excluded from knowledge documents.

## Measured results

"""
    write_text(REPO_ROOT / "docs/DOCS_BUILD.md", guide + report)


if __name__ == "__main__":
    main()
