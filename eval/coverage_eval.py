"""Measure legacy and structured knowledge answers with identical frozen contexts."""

from __future__ import annotations

import argparse
import json
import logging
import os
import subprocess
from collections import Counter
from datetime import UTC, datetime
from pathlib import Path
from time import perf_counter

from dotenv import load_dotenv
from pydantic import BaseModel

from eval.coverage_inputs import CoverageCase, freeze_inputs, load_inputs
from eval.intent_eval import runtime_versions, source_hash
from eval.metrics import outcome_rates, percentile
from support_agent.config import REPO_ROOT, get_settings
from support_agent.data.doc_models import digest, json_text, write_text
from support_agent.graph.deps import GraphDeps
from support_agent.graph.nodes.knowledge import KnowledgePath
from support_agent.graph.state import ConversationState


class CoverageRecord(BaseModel):
    case: CoverageCase
    accepted: bool
    answer: str
    status: str
    error_type: str | None
    latency_s: float
    coverage: dict | None = None


def load_complete_run(
    path: Path, inputs: Path, split: str | None = None
) -> tuple[dict, list[CoverageRecord]]:
    """Validate saved measurements against all frozen cases before reporting."""
    lines = path.read_text().splitlines()
    saved_meta = json.loads(lines[0])
    selected_split = split if split is not None else saved_meta["split"]
    _, expected_cases = load_inputs(inputs, selected_split)
    saved_rows = [CoverageRecord.model_validate_json(line) for line in lines[1:]]
    if saved_meta["inputs_hash"] != digest(inputs.read_text()):
        raise ValueError("Coverage report inputs changed")
    if saved_meta["split"] != selected_split:
        raise ValueError("Coverage report split changed")
    if len({r.case.id for r in saved_rows}) != len(saved_rows):
        raise ValueError("Coverage report contains duplicate items")
    if {r.case.id: r.case.model_dump() for r in saved_rows} != {
        c.id: c.model_dump() for c in expected_cases
    }:
        raise ValueError("Coverage report requires complete identical frozen inputs")
    return saved_meta, saved_rows


def report(
    path: Path, meta: dict, rows: list[CoverageRecord], baseline: Path | None = None
) -> None:
    lines = [
        "# Evidence coverage answer-stage experiment",
        "",
        "Generated by `make eval-coverage`.",
        "",
    ]
    lines += [f"- {k}: `{json.dumps(v, sort_keys=True)}`" for k, v in meta.items()]
    lines += [
        "",
        "| Subset | Items | False accept | False reject | Accepted | P50 | P95 |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for subset in sorted({r.case.subset for r in rows}):
        selected = [r for r in rows if r.case.subset == subset]
        rates = outcome_rates([r.case.complete for r in selected], [r.accepted for r in selected])
        false_accept = (
            f"{rates.false_accept:.2%}" if any(not r.case.complete for r in selected) else "n/a"
        )
        false_reject = (
            f"{rates.false_reject:.2%}" if any(r.case.complete for r in selected) else "n/a"
        )
        latency = [r.latency_s for r in selected]
        lines.append(
            f"| {subset} | {len(selected)} | {false_accept} | "
            f"{false_reject} | {rates.accepted_count} | "
            f"{percentile(latency, 50):.4f}s | {percentile(latency, 95):.4f}s |"
        )
    lines += ["", "| Subset / status | Items |", "|---|---:|"]
    lines += [
        f"| {key} | {count} |"
        for key, count in sorted(Counter(f"{r.case.subset} / {r.status}" for r in rows).items())
    ]
    lines += ["", "| Rejected supported / accepted unsupported id | Status |", "|---|---|"]
    lines += [f"| {r.case.id} | {r.status} |" for r in rows if r.accepted != r.case.complete]
    lines += [
        "",
        "Controls use fictional passages and authored labels, not reviewed production data.",
        "Retrieval dev labels describe the corpus, not proof that these contexts cover every part.",
        "Acceptance is not answer accuracy. Source quote presence is not entailment verification.",
        "This measures the answer stage with frozen contexts and an unchanged gate.",
        "Failures remain in the denominator. Saved failures are never selectively rerun.",
        "",
    ]
    if baseline:
        from eval.coverage_compare import paired_lines

        lines.extend(paired_lines(meta, rows, baseline))
    write_text(path, "\n".join(lines).rstrip() + "\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--inputs", type=Path, required=True)
    parser.add_argument("--freeze", action="store_true")
    parser.add_argument("--split", choices=["dev", "test"], default="dev")
    parser.add_argument("--output", type=Path)
    parser.add_argument("--report", type=Path)
    parser.add_argument("--baseline", type=Path)
    parser.add_argument("--legacy", action="store_true")
    parser.add_argument("--report-only", action="store_true")
    args = parser.parse_args(argv)
    if args.freeze:
        freeze_inputs(
            REPO_ROOT / ".cache/retrieval/latest_run.json",
            REPO_ROOT / "eval/drafts/coverage_controls.yaml",
            REPO_ROOT / args.inputs,
        )
        return 0
    if not args.output or not args.report:
        parser.error("--output and --report are required for collection")
    if args.report_only:
        saved_meta, saved_rows = load_complete_run(
            REPO_ROOT / args.output, REPO_ROOT / args.inputs, args.split
        )
        report(
            REPO_ROOT / args.report,
            saved_meta,
            saved_rows,
            REPO_ROOT / args.baseline if args.baseline else None,
        )
        return 0
    load_dotenv(REPO_ROOT / ".env")
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    logging.getLogger("httpx").setLevel(logging.WARNING)
    settings = get_settings()
    input_meta, cases = load_inputs(REPO_ROOT / args.inputs, args.split)
    meta = {
        "git_sha": subprocess.check_output(["git", "rev-parse", "HEAD"], text=True).strip(),
        "code_hash": source_hash(
            [
                *list((REPO_ROOT / "src/support_agent").rglob("*.py")),
                *list((REPO_ROOT / "eval").glob("coverage*.py")),
                REPO_ROOT / "eval/legacy_knowledge.py",
            ]
        ),
        "config_hash": digest(json_text(settings.model_dump(mode="json"))),
        "prompt_hash": digest(
            (
                REPO_ROOT
                / (
                    "eval/prompts/coverage_round2_before.md"
                    if args.legacy
                    else "src/support_agent/graph/prompts/answer.md"
                )
            ).read_text()
        ),
        "inputs_hash": digest((REPO_ROOT / args.inputs).read_text()),
        "input_metadata": input_meta,
        "split": args.split,
        "date": datetime.now(UTC).isoformat(),
        "provider": os.environ.get("LLM_PROVIDER") or settings.llm.provider,
        "main_model": os.environ.get("LLM_MAIN_MODEL") or settings.llm.main_model,
        "model_options": {"temperature": settings.llm.temperature, **settings.llm.model_kwargs},
        "runtime": runtime_versions(),
    }
    output = REPO_ROOT / args.output
    existing: dict[str, CoverageRecord] = {}
    if output.exists():
        lines = output.read_text().splitlines()
        saved_meta = json.loads(lines[0])
        if {k: v for k, v in saved_meta.items() if k != "date"} != {
            k: v for k, v in meta.items() if k != "date"
        }:
            raise ValueError("Coverage cache provenance changed; choose a new output")
        records = [CoverageRecord.model_validate_json(line) for line in lines[1:]]
        existing = {r.case.id: r for r in records}
        expected = {c.id: c.model_dump() for c in cases}
        if len(existing) != len(records) or any(
            expected.get(r.case.id) != r.case.model_dump() for r in records
        ):
            raise ValueError("Coverage cache items changed or duplicated")
        meta = saved_meta
    with GraphDeps(settings) as deps:
        if args.legacy:
            from eval.legacy_knowledge import LegacyKnowledgePath

            path = LegacyKnowledgePath(deps)
        else:
            path = KnowledgePath(deps)
        for case in cases:
            if case.id in existing:
                continue
            state = ConversationState(
                rewritten_query=case.question, retrieval=case.chunks, trace=["retrieve"]
            )
            gate_update = path.gate(state)
            state = state.model_copy(update=gate_update)
            start = perf_counter()
            result = path.answer(state) if state.gate and state.gate.passed else path.handoff(state)
            coverage = result.get("coverage")
            row = CoverageRecord(
                case=case,
                accepted=result.get("handoff") is None,
                answer=result["answer"],
                status=result.get("answer_status", "gate_rejected"),
                error_type=result.get("answer_error_type"),
                latency_s=perf_counter() - start,
                coverage=coverage.model_dump() if hasattr(coverage, "model_dump") else coverage,
            )
            existing[case.id] = row
            temp = output.with_suffix(".tmp")
            write_text(
                temp,
                json.dumps(meta)
                + "\n"
                + "".join(
                    existing[c.id].model_dump_json() + "\n" for c in cases if c.id in existing
                ),
            )
            temp.replace(output)
            logging.info("coverage %d/%d %s %s", len(existing), len(cases), case.id, row.status)
    report(
        REPO_ROOT / args.report,
        meta,
        [existing[c.id] for c in cases],
        REPO_ROOT / args.baseline if args.baseline else None,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
