"""Re-score saved simulator transcripts with the current trajectory metrics.

Transcripts stay local (`items.jsonl` is gitignored); the report records each run's
file hash, the scenario set hash and the metric code SHA, so anyone holding the same
files gets the same numbers. No model is called.
"""

from __future__ import annotations

import argparse
import hashlib
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from eval.registry import file_hash, load_registry
from eval.run_record import git, is_dirty
from eval.sim.build_scenarios import load_scenarios
from eval.sim.metrics import aggregate_evaluations, evaluate_transcript
from eval.sim.models import ConversationTranscript
from support_agent.config import REPO_ROOT, get_settings
from support_agent.data.doc_models import write_text

SCENARIOS = REPO_ROOT / "eval/sets/scenarios_v1.jsonl"
REPORT = REPO_ROOT / "eval/reports/sim_rescore.md"


def _ci(entry: dict[str, Any]) -> str:
    if entry.get("mean") is None:
        return "n/a"
    return f"{entry['mean']:.2%} [{entry['low']:.2%}, {entry['high']:.2%}] (n={entry['n']})"


def rescore(run_dir: Path) -> dict[str, Any]:
    scenarios = {s.id: s for s in load_scenarios(SCENARIOS)}
    lines = (run_dir / "items.jsonl").read_text(encoding="utf-8").splitlines()
    transcripts = [ConversationTranscript.model_validate_json(line) for line in lines if line]
    stats = get_settings().eval
    evaluations = [evaluate_transcript(scenarios[t.scenario_id], t) for t in transcripts]
    return aggregate_evaluations(
        evaluations,
        n_resamples=stats.stats.n_resamples,
        seed=stats.sim.seed,
        alpha=stats.stats.alpha,
    )


def render(runs: list[Path]) -> str:
    entry = load_registry()["scenarios_v1"]
    lines = [
        "# Simulator transcripts re-scored with the current metrics",
        "",
        "Generated by `make eval-sim-rescore`. Do not edit by hand.",
        "",
        f"- Metric code SHA: `{git('rev-parse', 'HEAD')}` (dirty: {is_dirty()})",
        f"- Scenarios: `scenarios_v1@{entry.version}` (`{file_hash(SCENARIOS)}`)",
        f"- Date (UTC): {datetime.now(UTC):%Y-%m-%d}",
        "",
        "Fact retention counts only checkpoints whose turn the conversation reached with a",
        "probe that did not restate the fact; before, a checkpoint after the simulated user's",
        "last turn counted as a miss.",
        "",
        "| Run | Items sha256 | Conversations | Task success | Fact checkpoints probed "
        "| Fact retention |",
        "|---|---|---:|---|---:|---|",
    ]
    for run in runs:
        agg = rescore(run)
        digest = hashlib.sha256((run / "items.jsonl").read_bytes()).hexdigest()[:12]
        reached = agg["fact_checkpoints"]
        lines.append(
            f"| `{run.name}` | `{digest}` | {agg['n_runs']} | {_ci(agg['task_success'])} | "
            f"{reached['reached']}/{reached['total']} | {_ci(agg['fact_retention'])} |"
        )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("runs", nargs="+", type=Path, help="saved sim run directories")
    parser.add_argument("--output", type=Path, default=REPORT)
    args = parser.parse_args(argv)
    write_text(args.output, render(args.runs))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
