"""Render multi-turn baseline and simulator validity reports."""

from __future__ import annotations

import subprocess
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from eval.e2e_speed import run_config_hash
from eval.sim.models import ConversationTranscript
from support_agent.config import REPO_ROOT, Settings
from support_agent.llm import resolve_model


def _git_sha() -> str:
    try:
        return subprocess.check_output(
            ["git", "-c", f"safe.directory={REPO_ROOT}", "rev-parse", "HEAD"],
            cwd=REPO_ROOT,
            text=True,
        ).strip()
    except Exception:
        return "unknown"


def _reached(aggregate: dict[str, Any]) -> str:
    """Checkpoints the conversations reached; fact retention is scored only on these."""
    counts = aggregate.get("fact_checkpoints") or {}
    return f"{counts.get('reached', 0)}/{counts.get('total', 0)}"


def _fmt_ci(entry: dict[str, Any], *, pct: bool = False) -> str:
    mean = entry.get("mean")
    if mean is None:
        return "n/a"
    low = entry.get("low")
    high = entry.get("high")
    scale = 100.0 if pct else 1.0
    suffix = "%" if pct else ""
    if low is None or high is None:
        return f"{mean * scale:.2f}{suffix}"
    return f"{mean * scale:.2f}{suffix} [{low * scale:.2f}{suffix}, {high * scale:.2f}{suffix}]"


def render_sim_report(
    settings: Settings,
    aggregate: dict[str, Any],
    *,
    dataset_version: str,
    split: str,
    subset: str,
    repeats: int,
    simulator_model: str,
) -> str:
    fast_name, _ = resolve_model("fast", settings.llm)
    main_name, _ = resolve_model("main", settings.llm)
    wrong = aggregate["wrong_customer_access"]
    lines = [
        "# Multi-turn simulation baseline report",
        "",
        "Generated by `make eval-sim`. Do not edit by hand.",
        "",
        f"- Git SHA: `{_git_sha()}`",
        f"- Config hash: `{run_config_hash(settings)}`",
        f"- Dataset: `scenarios_v1@{dataset_version}` (split=`{split}`, subset=`{subset}`)",
        f"- Repeats per scenario: {repeats}",
        f"- Agent models: fast=`{fast_name or 'unset'}`, main=`{main_name or 'unset'}`",
        f"- Simulator model: `{simulator_model}` (temperature=`{settings.eval.sim.temperature}`)",
        f"- Date (UTC): {datetime.now(UTC).date().isoformat()}",
        "",
        "## Overall trajectory metrics (95% bootstrap CI)",
        "",
        "| Metric | Value | n |",
        "|---|---:|---:|",
        f"| Task success | {_fmt_ci(aggregate['task_success'], pct=True)} | "
        f"{aggregate['task_success']['n']} |",
        f"| Tool call precision | {_fmt_ci(aggregate['tool_call_precision'], pct=True)} | "
        f"{aggregate['tool_call_precision']['n']} |",
        f"| Tool call recall | {_fmt_ci(aggregate['tool_call_recall'], pct=True)} | "
        f"{aggregate['tool_call_recall']['n']} |",
        f"| Wrong customer access | {wrong['count']}/{wrong['total']} "
        f"(Wilson [{wrong['wilson_low'] * 100:.2f}%, {wrong['wilson_high'] * 100:.2f}%]) | "
        f"{wrong['total']} |",
        f"| Turns to success | {_fmt_ci(aggregate['turns_to_success'])} | "
        f"{aggregate['turns_to_success']['n']} |",
        f"| Redundant questions / conv | {_fmt_ci(aggregate['redundant_questions'])} | "
        f"{aggregate['redundant_questions']['n']} |",
        f"| Fact retention | {_fmt_ci(aggregate['fact_retention'], pct=True)} | "
        f"{aggregate['fact_retention']['n']} |",
        f"| Fact checkpoints reached | {_reached(aggregate)} | "
        f"{aggregate.get('fact_checkpoints', {}).get('total', 0)} |",
        f"| Loop rate | {_fmt_ci(aggregate['loop_rate'], pct=True)} | "
        f"{aggregate['loop_rate']['n']} |",
        f"| Handoff appropriateness | {_fmt_ci(aggregate['handoff_appropriate'], pct=True)} | "
        f"{aggregate['handoff_appropriate']['n']} |",
        f"| Run error rate | {aggregate['error_rate'] * 100:.2f}% | {aggregate['n_runs']} |",
        "",
    ]

    repeat_std = aggregate.get("repeat_task_success_mean_std")
    if repeat_std is not None:
        lines.extend(
            [
                f"- Repeat variance (mean per-scenario task-success std across {repeats} runs): "
                f"`{repeat_std:.4f}`",
                "",
            ]
        )

    lines.extend(
        [
            "## Breakdown by category",
            "",
            "| Category | n | Task success | Handoff ok | Redundant Q | Loop rate |",
            "|---|---:|---:|---:|---:|---:|",
        ]
    )
    for cat, stats in aggregate["categories"].items():
        lines.append(
            f"| {cat} | {stats['n']} | {stats['task_success'] * 100:.1f}% | "
            f"{stats['handoff_appropriate'] * 100:.1f}% | "
            f"{stats['redundant_questions_mean']:.2f} | {stats['loop_rate'] * 100:.1f}% |"
        )

    lines.extend(
        [
            "",
            "## Tokens per turn curve (baseline for Commit 28)",
            "",
            "| Turn | Conversations | Mean input tokens | P95 input tokens |",
            "|---:|---:|---:|---:|",
        ]
    )
    for point in aggregate["tokens_per_turn_curve"]:
        lines.append(
            f"| {point['turn']} | {point['n']} | {point['mean_input_tokens']:.1f} | "
            f"{point['p95_input_tokens']} |"
        )
    if not aggregate["tokens_per_turn_curve"]:
        lines.append("| (none) | 0 | 0.0 | 0 |")
    lines.append("")
    return "\n".join(lines)


def render_validity_template(
    transcripts: list[ConversationTranscript],
    *,
    sample_size: int = 10,
    run_dir: Path | None = None,
) -> str:
    """Export a 10-transcript review table separating simulator errors from agent errors."""
    chosen = transcripts[:sample_size]
    lines = [
        "# Simulator validity review",
        "",
        "Manually review sampled transcripts to separate simulator mistakes from agent mistakes.",
        "",
        f"- Source run: `{run_dir}`" if run_dir is not None else "- Source run: `(local)`",
        f"- Sampled transcripts: {len(chosen)}",
        "",
        "| Scenario | Repeat | Turns | Stop | Stayed in role? (yes/no) | "
        "Invented facts? (yes/no) | Notes |",
        "|---|---:|---:|---|---|---|---|",
    ]
    for tr in chosen:
        lines.append(
            f"| `{tr.scenario_id}` | {tr.repeat_index} | {len(tr.turns)} | "
            f"`{tr.stop_reason}` | pending | pending | |"
        )
    lines.append("")
    return "\n".join(lines)
