"""Which saved eval items could the answer-budget fit (28c) change? No model is called.

The fit only acts when the answer prompt exceeds the answer budget. For each item that
reached the answer step, this script computes an upper bound on that prompt from the saved
rows: the task prompt plus every source the item retrieved (a part's saved sources; for the
whole route, the longest chunk of each retrieved section in `data/processed/chunks.jsonl`).
Items under the budget by this bound got the same prompt before and after the fix.
Rows stay local (`items.jsonl` is gitignored); the report records their hashes.
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import json
from pathlib import Path
from typing import Any

from langchain_core.messages import HumanMessage, SystemMessage

from eval.run_record import git, is_dirty
from support_agent.config import REPO_ROOT, get_settings
from support_agent.context.budget import ApproxTokenCounter
from support_agent.data.doc_models import write_text
from support_agent.graph.handoff import PROMPTS

CHUNKS = REPO_ROOT / "data/processed/chunks.jsonl"
REPORT = REPO_ROOT / "eval/reports/answer_budget_exposure.md"
# Tags and numbering around each source in the rendered prompt, generously rounded up.
SOURCE_OVERHEAD_CHARS = 80


def _value(raw: Any) -> Any:
    return ast.literal_eval(raw) if isinstance(raw, str) else raw


def _passed(gate: Any) -> bool:
    gate = _value(gate)
    return bool(gate) and bool(gate.get("passed"))


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:12]


def longest_by_section(chunks: Path = CHUNKS) -> dict[str, str]:
    longest: dict[str, str] = {}
    for line in chunks.read_text(encoding="utf-8").splitlines():
        row = json.loads(line)
        text = f"{row['heading_path']}\n{row['text']}"
        if len(text) > len(longest.get(row["section_id"], "")):
            longest[row["section_id"]] = text
    return longest


def upper_bound(payload: dict[str, Any], texts: dict[str, str], count: Any) -> int | None:
    """Tokens the answer prompt could have had at most, or None if it never reached answer."""
    parts = payload.get("parts") or []
    if payload.get("route_source") == "parts":
        passed = [p for p in parts if _passed(p.get("gate"))]
        if not passed:
            return None
        prompt = (PROMPTS / "answer_parts.md").read_text(encoding="utf-8")
        sources = [
            f"{p['text']}\n{s.get('heading_path', '')}\n{s.get('text', '')}"
            for p in passed
            for s in _value(p.get("retrieved_sources")) or []
        ]
    else:
        if not _passed(payload.get("gate")):
            return None
        prompt = (PROMPTS / "answer.md").read_text(encoding="utf-8")
        ids = payload.get("retrieved_section_ids") or []
        sources = [texts.get(section, "") for section in ids]
    body = "\n".join(source + " " * SOURCE_OVERHEAD_CHARS for source in sources)
    question = str((payload.get("item") or {}).get("question", ""))
    return int(
        count.count_message(SystemMessage(content=prompt))
        + count.count_message(HumanMessage(content=f"{question}\n{body}"))
    )


def render(runs: list[Path]) -> str:
    settings = get_settings()
    count = ApproxTokenCounter(
        chars_per_token=settings.context.chars_per_token,
        message_overhead=settings.context.message_overhead_tokens,
    )
    budget = settings.context.profile_for("answer").total_tokens
    texts = longest_by_section()
    lines = [
        "# Answer-budget fit: which saved eval items it could change",
        "",
        "Generated by `make eval-answer-budget-exposure`. Do not edit by hand.",
        "",
        f"- Code SHA: `{git('rev-parse', 'HEAD')}` (dirty: {is_dirty()})",
        f"- Answer budget: {budget} tokens; chunks file sha256 `{_sha(CHUNKS)}`",
        "",
        "The bound counts every retrieved source, so it is never below the real prompt. An",
        "item under the budget by this bound sent the same prompt with and without the fit.",
        "",
        "| Run | Items sha256 | Items | Reached answer | Max bound (tokens) | Over budget |",
        "|---|---|---:|---:|---:|---|",
    ]
    for run in runs:
        rows = [
            json.loads(line)
            for line in (run / "items.jsonl").read_text(encoding="utf-8").splitlines()
            if line
        ]
        bounds = {row["id"]: upper_bound(row["payload"], texts, count) for row in rows}
        reached = {key: value for key, value in bounds.items() if value is not None}
        over = sorted(key for key, value in reached.items() if value > budget)
        lines.append(
            f"| `{run.name}` | `{_sha(run / 'items.jsonl')}` | {len(rows)} | {len(reached)} | "
            f"{max(reached.values(), default=0)} | "
            f"{', '.join(f'`{key}`' for key in over) or 'none'} |"
        )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("runs", nargs="+", type=Path, help="saved e2e or multipart run dirs")
    parser.add_argument("--output", type=Path, default=REPORT)
    args = parser.parse_args(argv)
    write_text(args.output, render(args.runs))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
