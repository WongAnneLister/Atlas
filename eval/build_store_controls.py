"""Build and freeze answerable store controls: single-store questions with known answers."""

from __future__ import annotations

import argparse
import json
import logging
import re
from pathlib import Path

import yaml
from pydantic import BaseModel, ConfigDict, Field

from eval.build_holdout import VERSIONS as HOLDOUTS
from eval.common import load_items, load_sections, near_duplicate, save_items, set_hash
from eval.schema import EvalItem, Section
from support_agent.config import REPO_ROOT, EvalSettings, StoreScopeSettings, get_settings
from support_agent.data.doc_models import digest, write_text
from support_agent.retrieval.scope import requested_stores, section_store

log = logging.getLogger(__name__)
DRAFT = Path("eval/drafts/store_controls.yaml")
OUTPUT = Path("eval/sets/store_controls_v1.jsonl")
REPORT = Path("eval/reports/store_controls.md")
SOURCE_PREFIX = "controls:store_v1"
_FAQ = re.compile(r"Regarding “(.+?)”:\s*\n\n(.+?)(?=\n\nRegarding “|\Z)", re.S)


class ControlItem(BaseModel):
    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)
    q: str = Field(min_length=1)
    faq: str = Field(pattern=r"^[0-9a-f]{12}$")


class ControlFamily(BaseModel):
    model_config = ConfigDict(extra="forbid")
    note: str
    items: list[ControlItem] = Field(min_length=1)


class ControlDraft(BaseModel):
    model_config = ConfigDict(extra="forbid")
    families: dict[str, ControlFamily]


def faq_index(sections: dict[str, Section]) -> dict[str, list[tuple[str, str]]]:
    """Map a FAQ question hash to every (section id, answer) that contains it."""
    index: dict[str, list[tuple[str, str]]] = {}
    for sid, section in sections.items():
        for match in _FAQ.finditer(section.text):
            key = digest(match.group(1).strip())[:12]
            index.setdefault(key, []).append((sid, " ".join(match.group(2).split())))
    return index


def build_controls(
    draft: ControlDraft,
    sections: dict[str, Section],
    existing: list[EvalItem],
    config: EvalSettings,
    scope: StoreScopeSettings,
) -> list[EvalItem]:
    errors: list[str] = []
    items: list[EvalItem] = []
    index = faq_index(sections)
    for family, group in draft.families.items():
        for control in group.items:
            stores = requested_stores(control.q, scope)
            hits = index.get(control.faq, [])
            if len(stores) != 1:
                errors.append(f"{control.q!r}: must name exactly one store")
                continue
            (store,) = stores
            gold = [sid for sid, _ in hits if section_store(sid, scope) == store]
            if not gold:
                errors.append(f"{control.q!r}: FAQ {control.faq} not found in {store} sections")
                continue
            for other in [*existing, *items]:
                if near_duplicate(control.q, other.question, config):
                    errors.append(f"{control.q!r}: near duplicate of {other.id}")
            answer = next(text for sid, text in hits if sid == gold[0])
            items.append(
                EvalItem(
                    id="store_control-" + digest(control.q),
                    group="basic_policy",
                    split="test",
                    question=control.q,
                    gold_sections=list(dict.fromkeys(gold)),
                    answer_points=[answer],
                    answerable=True,
                    source=f"{SOURCE_PREFIX}:{family}:faq:{control.faq}",
                    notes=json.dumps({"family": family, "store": store}, sort_keys=True),
                )
            )
    if errors:
        raise ValueError("Store control validation failed:\n" + "\n".join(errors))
    return items


def write_report(items: list[EvalItem], draft_hash: str, path: Path) -> None:
    families: dict[str, int] = {}
    for item in items:
        name = json.loads(item.notes)["family"]
        families[name] = families.get(name, 0) + 1
    lines = [
        "# Answerable store controls",
        "",
        "Generated by `make eval-store-controls-build`. Frozen before filter on/off runs.",
        "",
        f"- Draft file: `{DRAFT.as_posix()}`",
        f"- Draft hash: `{draft_hash}`",
        f"- Frozen set hash: `{set_hash(items)}`",
        f"- Items: {len(items)} (all answerable, all unreviewed)",
        "- Validation: each question names exactly one store; its FAQ exists in that",
        "  store's sections; no near duplicates of eval_v1, holdouts, or each other.",
        "",
        "| Family | Items |",
        "|---|---:|",
        *[f"| {name} | {count} |" for name, count in families.items()],
        "",
        "## Limits",
        "",
        "Questions are agent-authored paraphrases of FAQ questions; answers are the FAQ text.",
        "Gold sections are every section of the named store that contains the FAQ.",
        "This set measures false rejects only; it has no unanswerable items.",
    ]
    write_text(path, "\n".join(lines) + "\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="validate without writing files")
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    settings = get_settings()
    try:
        raw = (REPO_ROOT / DRAFT).read_text(encoding="utf-8")
        draft = ControlDraft.model_validate(yaml.safe_load(raw))
        existing = load_items(REPO_ROOT / settings.evaluation.sets_dir / "eval_v1.jsonl")
        for spec in HOLDOUTS.values():
            existing += load_items(REPO_ROOT / spec.output)
        items = build_controls(
            draft,
            load_sections(settings),
            existing,
            settings.evaluation,
            settings.retrieval.store_scope,
        )
    except (OSError, ValueError) as error:
        log.error("store control build failed: %s", error)
        return 1
    if not args.check:
        output = REPO_ROOT / OUTPUT
        if output.exists() and set_hash(load_items(output)) != set_hash(items):
            log.error("%s exists with different content; the controls are frozen", OUTPUT)
            return 1
        save_items(output, items)
        write_report(items, digest(raw), REPO_ROOT / REPORT)
    log.info("store controls: %d", len(items))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
