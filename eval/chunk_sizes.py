"""Chunk size distribution and hard-cap check for saved index build snapshots (28g).

Reads `data/processed/builds/<build_id>/chunks.jsonl` (checksum-verified) for each build id
and reports count, max, p99 and chunks over `chunk.max_tokens`, plus every chunk over
`chunk.hard_max_tokens`. No model or Milvus call. Exit code 1 if any build breaks the cap.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from eval.run_record import git, is_dirty
from support_agent.config import get_settings
from support_agent.data.doc_models import write_text
from support_agent.retrieval.chunking import ChunkSizeError, check_chunk_sizes, chunk_size_stats
from support_agent.retrieval.index_snapshot import build_chunk_hash, load_build_chunks


def report(build_ids: list[str]) -> tuple[str, bool]:
    settings = get_settings()
    lines = [
        "# Chunk sizes of index builds",
        "",
        "Generated by `make eval-chunk-sizes`. Do not edit by hand.",
        "",
        f"- Git SHA: `{git('rev-parse', 'HEAD')}` (dirty: {is_dirty()})",
        f"- chunk.max_tokens {settings.chunk.max_tokens}, "
        f"chunk.hard_max_tokens {settings.chunk.hard_max_tokens} (BGE tokenizer counts)",
        "",
        "| Build | Chunk hash | Chunks | Max | p99 | Over max_tokens | Hard cap check |",
        "|---|---|---:|---:|---:|---:|---|",
    ]
    failures: list[str] = []
    for build_id in build_ids:
        chunks = load_build_chunks(settings, build_id)
        stats = chunk_size_stats(chunks, settings.chunk)
        try:
            check_chunk_sizes(chunks, settings.chunk)
            verdict = "pass"
        except ChunkSizeError as error:
            verdict = "fail"
            failures.append(f"- `{build_id}`: {error}")
        lines.append(
            f"| `{build_id}` | `{build_chunk_hash(settings, build_id)[:12]}` | {stats.count} | "
            f"{stats.max_tokens} | {stats.p99_tokens} | {stats.over_max_tokens} | {verdict} |"
        )
    if failures:
        lines.extend(["", "## Chunks over the hard cap", "", *failures])
    return "\n".join(lines) + "\n", not failures


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("build_ids", nargs="+")
    parser.add_argument("--output", type=Path)
    args = parser.parse_args(argv)
    text, ok = report(args.build_ids)
    sys.stdout.write(text)
    if args.output:
        write_text(args.output, text)
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
