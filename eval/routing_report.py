"""Metadata-only reporting for paired dev routing experiments."""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path
from typing import Any

from eval.routing_eval import RoutingRecord, load_run, metrics, validate_pair
from support_agent.data.doc_models import write_text
from support_agent.graph.intents import INTENT_TO_PATH


def write_report(
    meta: dict[str, Any], rows: list[RoutingRecord], path: Path, baseline: Path | None
) -> None:
    runs = [("Candidate", meta, rows)]
    if baseline:
        old_meta, old = load_run(baseline)
        validate_pair(old_meta, old, meta, rows)
        runs.insert(0, ("Before", old_meta, old))
    lines = ["# Dev routing experiment", "", "Generated by `make eval-routing`.", ""]
    for label, metadata, _ in runs:
        lines += [f"## {label} provenance", ""]
        lines.extend(
            f"- {key}: `{json.dumps(value, sort_keys=True)}`" for key, value in metadata.items()
        )
    lines += [
        "",
        "## Route measurements",
        "",
        "| Run | Subset | Correct / labelled | Path match rate | Model failures |",
        "|---|---|---:|---:|---:|",
    ]
    for label, _, records in runs:
        for subset in ("dev_answerable", "controls"):
            selected = [r for r in records if r.item.source == subset]
            values = metrics(selected)
            rate = values["path_accuracy"]
            rate_text = f"{rate:.2%}" if rate is not None else "not measured"
            lines.append(
                f"| {label} | {subset} | {values['correct']}/{values['labelled']} | "
                f"{rate_text} | {values['failures']} |"
            )
    for label, _, records in runs:
        lines.append(
            f"\n- {label} no-answer route counts (no intent gold): "
            f"`{json.dumps(metrics(records)['unlabelled_paths'], sort_keys=True)}`"
        )
    if baseline:
        old_by_id = {r.item.id: r for r in runs[0][2]}
        successful = [
            r for r in rows if not r.parse_failed and not old_by_id[r.item.id].parse_failed
        ]
        lines += [
            "",
            "### Answerable questions with successful model calls in both runs",
            "",
            "| Run | Correct / paired questions | Path match rate |",
            "|---|---:|---:|",
        ]
        paired = [r for r in successful if r.item.source == "dev_answerable"]
        for label, records in (
            ("Before", [old_by_id[r.item.id] for r in paired]),
            ("Candidate", paired),
        ):
            values = metrics(records)
            rate = values["path_accuracy"]
            formatted = f"{rate:.2%}" if rate is not None else "not measured"
            lines.append(f"| {label} | {values['correct']}/{values['labelled']} | {formatted} |")
        lines += [
            "",
            "The primary table retains failures; this paired view separates call availability.",
        ]
    lines += [
        "",
        "## Answerable dev routes by group",
        "",
        "| Run | Group | A | B | C | D | E |",
        "|---|---|---:|---:|---:|---:|---:|",
    ]
    for label, _, records in runs:
        for group in sorted({r.item.group for r in records if r.item.source == "dev_answerable"}):
            counts = Counter(
                INTENT_TO_PATH[r.predicted].value
                for r in records
                if r.item.source == "dev_answerable" and r.item.group == group
            )
            lines.append(
                f"| {label} | {group} | " + " | ".join(str(counts[p]) for p in "ABCDE") + " |"
            )
    if baseline:
        previous = {r.item.id: r for r in runs[0][2]}
        lines += [
            "",
            "## Changed routes",
            "",
            "| Id | Source | Before | Candidate | Expected |",
            "|---|---|---|---|---|",
        ]
        for row in rows:
            before_path = INTENT_TO_PATH[previous[row.item.id].predicted]
            after_path = INTENT_TO_PATH[row.predicted]
            if before_path != after_path:
                lines.append(
                    f"| {row.item.id} | {row.item.source} | {before_path} | {after_path} | "
                    f"{row.item.expected_path or 'unlabelled'} |"
                )
    lines += [
        "",
        "## Limits",
        "",
        "Only dev questions are used; test questions are not classified by this experiment.",
        "Answerable retrieval questions target knowledge path B by benchmark design.",
        "This is not a human-reviewed intent label; some personal wording is ambiguous.",
        "No-answer questions have no invented intent/path gold and contribute route counts only.",
        "Controls are authored checks, not live traffic or held-out accuracy evidence.",
        "Correct routing does not establish answer accuracy, acceptance, or refusal safety.",
        "First-turn rewrite is a pass-through; this experiment isolates the shared classifier.",
        "Provider aliases are mutable; a single run can vary even at zero temperature.",
        "",
    ]
    write_text(path, "\n".join(lines))
