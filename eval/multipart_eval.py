DATASET = "multipart_v1"
REPORT = Path("eval/reports/multipart.md")


def read_dataset(split: str) -> tuple[str, list[MultipartItem]]:
    entry = load_registry()[DATASET]
    data = (REPO_ROOT / entry.path).read_bytes()
    if sha256(data).hexdigest() != entry.sha256:
        raise ValueError("Multipart data differs from its frozen registry entry")
    text = data.decode("utf-8")
    items = [MultipartItem.model_validate_json(line) for line in text.splitlines() if line.strip()]
    selected = [item for item in items if split == "all" or item.split == split]
    if not selected:
        raise ValueError(f"No multipart items for {split}")
    return text, selected


def collect(
    graph: Any,
    items: Sequence[MultipartItem],
    settings: Settings,
    build_id: str | None,
    *,
    workers: int = 1,
) -> list[E2ERecord]:
    """Run every item; records come back in input order whatever order items finish in."""
    threads = EvalThreads("multipart")
    done: dict[str, E2ERecord] = {}

    def run(item: MultipartItem) -> E2ERecord:
        result, latency, usage = _run_item(
            graph, item, settings.evaluation.customer_id, threads(item.split, item.id), TurnTrace()
        )
        return _record(item, result, latency, usage.first_token_at, usage.tokens(), usage)

    def keep(item: MultipartItem, record: E2ERecord) -> None:
        if record.build_id is not None and record.build_id != build_id:
            raise ValueError("Index build changed during multipart collection")
        if record.usage_by_model:
            record.estimated_cost_usd = cost_usd(record.usage_by_model, settings.costs)
        done[item.id] = record

    run_items(items, run, workers=workers, done=keep)
    return [done[item.id] for item in items]


def write_report(run: Run, output: Path) -> None:
    manifest = run.manifest
    if manifest.kind != "multipart":
        raise ValueError("Expected a multipart run")
    lines = [
        "# Multipart evaluation",
        "",
        "Generated by `make eval-multipart` from saved run items.",
        "",
        f"- Git SHA and dirty state: `{manifest.git_sha}`, {manifest.dirty}",
        f"- Config hash: `{manifest.config_hash}`",
        f"- Split and UTC start: {manifest.split}, {manifest.started_at}",
        f"- Dataset versions: {manifest.datasets}",
        f"- Index build: {manifest.source.get('build_id') or 'unknown'}",
        f"- Models: {manifest.models}",
        *speed_lines(manifest.source),
        "- Counts include the routing outcomes of the full graph.",
        "",
        "| Split | Group | Metric | Estimate and confidence interval |",
        "|---|---|---|---|",
    ]
    groups: dict[tuple[str, str, str], list[bool | float]] = defaultdict(list)
    for row in run.items:
        split = row.payload["item"]["split"]
        for name, value in row.metrics.items():
            groups[split, row.group or "unknown", name].append(value)
    bootstrap = (run.metrics.bootstrap or get_settings().eval.stats).model_dump()
    comparable = latency_comparable(manifest.source)
    for (split, group, name), values in sorted(groups.items()):
        statistic = resolve_statistic(run.metrics.statistics.get(name, "mean"))
        summary = summarize(values, statistic, **bootstrap)
        formatted = format_summary(summary, rate=summary.count is not None)
        if not comparable and is_latency_metric(name):
            formatted += f" ({NOT_COMPARABLE})"
        lines.append(f"| {split} | {group} | {name} | {formatted} |")
    write_text(output, "\n".join(lines) + "\n")


def write_human_sample(
    records: Sequence[E2ERecord],
    path: Path,
    *,
    seed: int,
    size: int | None = None,
    judged: Sequence[JudgeRecord] = (),
) -> None:
    partials = sorted(
        (record for record in records if partial_answer(record)), key=lambda r: r.item.id
    )
    if size is not None and size < 1:
        raise ValueError("Sample size must be positive")
    if size is not None and size < len(partials):
        partials = sorted(Random(seed).sample(partials, size), key=lambda r: r.item.id)
    findings = {record.item_id: record for record in judged}
    fields = [
        "item_id",
        "split",
        "question",
        "answer",
        "parts",
        "cited_sources",
        "judge_flagged",
        "judge_findings",
        "answered_parts_correct",
        "handoffs_supported_by_evidence",
        "review_notes",
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields)
        writer.writeheader()
        for record in partials:
            payload = partial_payload(record)
            verdict = findings.get(record.item.id)
            writer.writerow(
                {
                    "item_id": record.item.id,
                    "split": record.item.split,
                    "question": payload["question"],
                    "answer": payload["answer"],
                    "parts": json.dumps(payload["parts"], ensure_ascii=False),
                    "cited_sources": json.dumps(payload["cited_sources"], ensure_ascii=False),
                    "judge_flagged": str(verdict.flagged).lower() if verdict else "",
                    "judge_findings": json.dumps(verdict.claims, ensure_ascii=False)
                    if verdict
                    else "",
                }
            )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--split", choices=("dev", "test", "all"), default="test")
    parser.add_argument("--run-dir", type=Path, help="report or review a saved run")
    parser.add_argument("--run-root", type=Path, default=RUNS)
    parser.add_argument("--report", type=Path, default=REPORT)
    parser.add_argument(
        "--sample-output", type=Path, help="local review CSV for saved partial answers"
    )
    parser.add_argument("--sample-size", type=int)
    parser.add_argument(
        "--judge", action="store_true", help="judge saved partial answers with the main model"
    )
    add_speed_arguments(parser)
    args = parser.parse_args(argv)
    if (args.judge or args.sample_output) and not args.run_dir:
        parser.error("Use --run-dir with --judge or --sample-output")
    if args.judge and not args.sample_output:
        parser.error("Use --sample-output to save the judge findings")
    if args.sample_size is not None and (not args.sample_output or args.sample_size < 1):
        parser.error("--sample-size requires --sample-output and a positive size")

    if args.run_dir:
        run = read_run(REPO_ROOT / args.run_dir)
        write_report(run, REPO_ROOT / args.report)
        if args.sample_output:
            _, records = unpack(run)
            judged = []
            if args.judge:
                load_dotenv(REPO_ROOT / ".env", override=False)
                get_settings.cache_clear()
                settings = get_settings()
                prompt = (REPO_ROOT / "eval/prompts/judge_partial.md").read_text(encoding="utf-8")
                with GraphDeps(settings) as deps:
                    model = deps.model("main")
                    judged = [
                        judge_partial_record(model, prompt, record)
                        for record in records
                        if partial_answer(record)
                    ]
            seed = (
                run.manifest.seed
                if run.manifest.seed is not None
                else get_settings().eval.stats.seed
            )
            write_human_sample(
                records,
                REPO_ROOT / args.sample_output,
                seed=seed,
                size=args.sample_size,
                judged=judged,
            )
        return 0

    text, items = read_dataset(args.split)
    load_dotenv(REPO_ROOT / ".env", override=False)
    get_settings.cache_clear()
    settings = get_settings()
    if settings.chaos.enabled or settings.gate.threshold is None:
        parser.error("Multipart collection requires a tuned gate with chaos disabled")
    speed: SpeedOptions = speed_options(args, settings, parser)
    dirty = is_dirty()
    corpus_hash = digest(json_text([s.model_dump() for s in load_sections(settings).values()]))
    metadata = _metadata(settings, args.split, text, corpus_hash)
    metadata.build_id = configured_build_id(settings)
    with TemporaryDirectory(prefix="atlas-multipart-") as folder:
        scratch = scratch_settings(settings, Path(folder))
        with (
            rerank_scores(scratch, speed.rerank_cache) as scores,
            GraphDeps(scratch, reranker_factory=scores.factory()) as deps,
        ):
            records = collect(
                build_graph(deps), items, scratch, metadata.build_id, workers=speed.workers
            )
            _record_speed(metadata, speed, scores.summary())
    command = ["eval-multipart", *(sys.argv[1:] if argv is None else argv)]
    run = prepare_e2e(metadata, records, dirty=dirty, command=command)
    if broken := invalid_run_message(run):
        sys.stderr.write(f"Invalid run, nothing reported: {broken}\n")
        return INVALID_RUN_STATUS
    path = write_run(
        run.manifest, run.items, metrics=run.metrics, root=args.run_root, suffix=uuid4().hex
    )
    write_report(run, REPO_ROOT / args.report)
    sys.stdout.write(f"Run record: {path}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
