DEFAULT_REPORT = REPO_ROOT / "eval" / "reports" / "memory_short.md"
DEFAULT_RUN_ROOT = REPO_ROOT / "eval" / "runs"

ARMS: tuple[tuple[str, bool, bool, bool], ...] = (
    ("baseline_c28", False, False, False),
    ("facts_only", True, True, False),
    ("compaction_only", True, False, True),
    ("both", True, True, True),
)


def _git_sha() -> str:
    try:
        return subprocess.check_output(
            ["git", "-c", f"safe.directory={REPO_ROOT}", "rev-parse", "HEAD"],
            cwd=REPO_ROOT,
            text=True,
        ).strip()
    except Exception:
        return "unknown"


def _arm_summary(transcripts: list[ConversationTranscript], agg: dict[str, Any]) -> dict[str, Any]:
    total_in = 0
    total_cache_read = 0
    total_compactions = 0
    total_sum_calls = 0
    latencies: list[float] = []
    for tr in transcripts:
        for turn in tr.turns:
            latencies.append(turn.latency_s)
            total_compactions += turn.compaction_events
            total_sum_calls += turn.summariser_calls
            for call in turn.context_calls:
                total_in += int(call.get("input_tokens", 0) or 0)
                total_cache_read += int(call.get("cache_read_tokens", 0) or 0)
    n_conv = max(1, len(transcripts))
    lat_sorted = sorted(latencies)
    p50 = lat_sorted[len(lat_sorted) // 2] if lat_sorted else 0.0
    p95 = (
        lat_sorted[min(len(lat_sorted) - 1, int(0.95 * (len(lat_sorted) - 1)))]
        if lat_sorted
        else 0.0
    )
    return {
        "aggregate": agg,
        "total_input_tokens": total_in,
        "total_cache_read_tokens": total_cache_read,
        "cache_hit_ratio": (total_cache_read / total_in) if total_in > 0 else 0.0,
        "compactions_per_conv": total_compactions / n_conv,
        "total_compactions": total_compactions,
        "summariser_calls": total_sum_calls,
        "mean_tokens_per_turn": statistics.mean(
            [t.input_tokens for tr in transcripts for t in tr.turns] or [0]
        ),
        "turn_latency_p50_s": p50,
        "turn_latency_p95_s": p95,
    }


def render_memory_report(
    settings: Settings,
    results: dict[str, dict[str, Any]],
    *,
    n_scenarios: int,
    repeats: int,
    simulator_model: str,
) -> str:
    fast_name, _ = resolve_model("fast", settings.llm)
    main_name, _ = resolve_model("main", settings.llm)

    def _fmt(entry: dict[str, Any], pct: bool = False) -> str:
        mean = entry.get("mean")
        if mean is None:
            return "n/a"
        scale = 100.0 if pct else 1.0
        suf = "%" if pct else ""
        lo, hi = entry["low"] * scale, entry["high"] * scale
        return f"{mean * scale:.2f}{suf} [{lo:.2f}{suf}, {hi:.2f}{suf}]"

    lines = [
        "# Short-term memory evaluation and ablation report",
        "",
        "Generated by `make eval-memory-short`. Do not edit by hand.",
        "",
        f"- Git SHA: `{_git_sha()}`",
        f"- Config hash: `{run_config_hash(settings)}`",
        f"- Scenarios: {n_scenarios} (nightly test + long-conversation) x {repeats} repeat(s)",
        f"- Agent models: fast=`{fast_name or 'unset'}`, main=`{main_name or 'unset'}`",
        f"- Simulator model: `{simulator_model}`",
        f"- Date (UTC): {datetime.now(UTC).date().isoformat()}",
        "",
        "## Ablation comparison (95% bootstrap CI)",
        "",
        "| Arm | Task success | Fact retention | Redundant Q | Cache hit ratio | "
        "Compactions/conv | Summariser calls | Mean tok/turn | Latency P50/P95 (s) |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for arm_name, data in results.items():
        agg = data["aggregate"]
        lines.append(
            f"| `{arm_name}` | {_fmt(agg['task_success'], True)} | "
            f"{_fmt(agg['fact_retention'], True)} | {_fmt(agg['redundant_questions'])} | "
            f"{data['cache_hit_ratio'] * 100:.1f}% | {data['compactions_per_conv']:.2f} | "
            f"{data['summariser_calls']} | {data['mean_tokens_per_turn']:.1f} | "
            f"{data['turn_latency_p50_s']:.2f} / {data['turn_latency_p95_s']:.2f} |"
        )
    lines.append("")
    return "\n".join(lines)


def _select(scenarios: list[Scenario], *, include_long: bool) -> list[Scenario]:
    chosen = [s for s in scenarios if s.split == "test" and s.nightly]
    if include_long:
        long_test = [
            s for s in scenarios if s.split == "test" and s.category == "long_conversation"
        ]
        # Keep first long conversation (capped to 14 turns if needed? No, use real scenario as-is!)
        seen = {s.id for s in chosen}
        for s in long_test[:1]:
            if s.id not in seen:
                chosen.append(s)
    return chosen


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Run short-term memory ablation eval.")
    parser.add_argument("--scenarios", type=Path, default=DEFAULT_SCENARIOS)
    parser.add_argument("--repeats", type=int, default=1)
    parser.add_argument("--include-long", action="store_true", default=True)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    parser.add_argument("--run-root", type=Path, default=DEFAULT_RUN_ROOT)
    args = parser.parse_args(argv)

    base_settings = get_settings().model_copy(deep=True)
    base_settings.api.rate_limit.per_customer = 10000
    base_settings.api.rate_limit.per_ip = 10000

    scenarios = _select(load_scenarios(args.scenarios), include_long=args.include_long)
    by_id = {s.id: s for s in scenarios}
    sim_model, sim_name = build_simulator_model(base_settings)
    simulator = UserSimulator(sim_model, model_name=sim_name)

    results: dict[str, dict[str, Any]] = {}
    arm_transcripts: dict[str, list[ConversationTranscript]] = {}
    for arm_name, enabled, facts_on, compact_on in ARMS:
        settings = base_settings.model_copy(deep=True)
        settings.memory.short_term.enabled = enabled
        settings.memory.short_term.pinned_facts_enabled = facts_on
        settings.memory.short_term.compaction_enabled = compact_on

        order_service = OrderService(platform=settings)
        graph_deps = GraphDeps(settings=settings, order_service=order_service)
        try:
            transcripts = asyncio.run(
                run_suite(
                    settings,
                    scenarios,
                    simulator=simulator,
                    graph_deps=graph_deps,
                    order_service=order_service,
                    repeats=args.repeats,
                )
            )
        finally:
            order_service.close()
        arm_transcripts[arm_name] = transcripts

        evals = [
            evaluate_transcript(
                by_id[tr.scenario_id], tr, loop_threshold=settings.eval.sim.loop_threshold
            )
            for tr in transcripts
        ]
        agg = aggregate_evaluations(
            evals,
            n_resamples=settings.eval.stats.n_resamples,
            seed=settings.eval.sim.seed,
            alpha=settings.eval.stats.alpha,
        )
        results[arm_name] = _arm_summary(transcripts, agg)

    run_dir = args.run_root / f"memory-short-{datetime.now(UTC):%Y%m%d}-{uuid4().hex[:8]}"
    run_dir.mkdir(parents=True, exist_ok=True)
    write_text(
        run_dir / "items.jsonl",
        "".join(
            json.dumps({"arm": arm, "transcript": tr.model_dump(mode="json")}) + "\n"
            for arm, transcripts in arm_transcripts.items()
            for tr in transcripts
        ),
    )
    if broken := invalid_arms_message(arm_transcripts):
        sys.stderr.write(f"Invalid run, nothing reported: {broken}\nRows kept in {run_dir}\n")
        return INVALID_RUN_STATUS
    write_text(run_dir / "metrics.json", json.dumps(results, indent=2) + "\n")
    write_text(
        args.report,
        render_memory_report(
            base_settings,
            results,
            n_scenarios=len(scenarios),
            repeats=args.repeats,
            simulator_model=sim_name,
        ),
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
