"""Compare seeded PostgreSQL and SQLite orders without calling an LLM."""

import logging
from datetime import datetime
from pathlib import Path
from tempfile import TemporaryDirectory
from zoneinfo import ZoneInfo

from pydantic import SecretStr
from sqlalchemy import select

from eval.e2e_eval import _git_sha
from support_agent.config import REPO_ROOT, get_settings
from support_agent.data.doc_models import digest, json_text, write_text
from support_agent.db.migrate import upgrade
from support_agent.db.scratch import scratch_database
from support_agent.orders.seed import generate_dataset
from support_agent.orders.service import OrderService
from support_agent.orders.tables import metadata


def compare_orders(
    sqlite: OrderService, postgres: OrderService, limit: int
) -> tuple[int, int, list[str]]:
    customers = sqlite.list_customers(limit)
    if customers != postgres.list_customers(limit):
        return len(customers), 0, ["customers"]
    order_count = 0
    differences: list[str] = []
    for customer in customers:
        owner = customer.customer_id
        expected = sqlite.list_recent_orders(owner, limit)
        order_count += len(expected)
        if expected != postgres.list_recent_orders(owner, limit):
            differences.append(f"{owner} recent orders")
        for order in expected:
            order_id = order.order_id
            if order != postgres.get_order(order_id, owner):
                differences.append(f"{order_id} detail")
            if sqlite.get_tracking(order_id, owner) != postgres.get_tracking(order_id, owner):
                differences.append(f"{order_id} tracking")
    return len(customers), order_count, differences


def compare_tables(
    sqlite: OrderService, postgres: OrderService
) -> tuple[dict[str, int], list[str]]:
    counts: dict[str, int] = {}
    differences: list[str] = []
    with sqlite.repository.connection() as left, postgres.repository.connection() as right:
        for table in metadata.sorted_tables:
            statement = select(table).order_by(*table.primary_key.columns)
            rows = left.execute(statement).all()
            counts[table.name] = len(rows)
            if rows != right.execute(statement).all():
                differences.append(f"{table.name} table rows")
    return counts, differences


def main() -> int:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    settings = get_settings()
    dataset = generate_dataset(settings)
    with (
        TemporaryDirectory(prefix="atlas-orders-parity-") as directory,
        scratch_database(settings) as url,
    ):
        postgres_settings = settings.model_copy(
            update={"database_url": SecretStr(url.render_as_string(hide_password=False))}
        )
        postgres_settings.db = settings.db.model_copy(update={"backend": "postgres"})
        postgres = OrderService(platform=postgres_settings)
        sqlite = OrderService(Path(directory) / "orders.sqlite", platform=settings)
        try:
            upgrade(postgres.repository.engine)
            sqlite.repository.replace(dataset)
            postgres.repository.replace(dataset)
            customer_count, order_count, mismatches = compare_orders(
                sqlite, postgres, max(settings.orders.n_customers, settings.orders.n_orders)
            )
            counts, table_mismatches = compare_tables(sqlite, postgres)
            mismatches.extend(table_mismatches)
        finally:
            sqlite.close()
            postgres.close()

    lines = [
        "# SQLite and PostgreSQL order parity",
        "",
        "Generated by `make eval-orders-parity`.",
        "",
        f"- Git SHA (base revision when run): `{_git_sha()}`",
        f"- Config hash: `{digest(json_text(settings.model_dump(mode='json')))}`",
        f"- Run date (Tokyo): {datetime.now(ZoneInfo('Asia/Tokyo')).date().isoformat()}",
        f"- Dataset version: mock-orders-v1, catalog hash `{dataset.metadata.catalog_hash}`",
        "- Model names: none.",
        "- Eval split: full synthetic seed.",
        f"- Service comparison: {customer_count} customers, {order_count} orders.",
        f"- Mismatches: **{len(mismatches)}**",
        "",
        "| Table | Seeded rows |",
        "|---|---:|",
        *[f"| {name} | {count} |" for name, count in counts.items()],
        "",
        *[f"- Mismatch: {entry}" for entry in mismatches],
    ]
    write_text(REPO_ROOT / "eval/reports/orders_parity.md", "\n".join(lines).rstrip() + "\n")
    logging.info(
        "Compared %d customers and %d orders, %d mismatches",
        customer_count,
        order_count,
        len(mismatches),
    )
    return int(bool(mismatches))


if __name__ == "__main__":
    raise SystemExit(main())
