"""Reproduce dataset counts and review status, without retrieval or answer-quality metrics."""

from __future__ import annotations

import json
import subprocess
from collections import Counter
from datetime import UTC, datetime

from eval.common import load_items, set_hash
from eval.schema import GROUPS
from eval.validate_set import validate_current
from support_agent.config import REPO_ROOT, get_settings
from support_agent.data.doc_models import digest, json_text, write_text


def main() -> None:
    settings = get_settings()
    folder = REPO_ROOT / settings.evaluation.sets_dir
    items = load_items(folder / "eval_v1.jsonl")
    manifest = json.loads((folder / "manifest.json").read_text(encoding="utf-8"))
    failures = validate_current()
    counts = Counter((item.group, item.split) for item in items)
    reviewed = sum(item.reviewed for item in items)
    model_sections = {
        sid for item in items if item.group == "model_number" for sid in item.gold_sections
    }
    sha = subprocess.check_output(
        ["git", "-c", f"safe.directory={REPO_ROOT.as_posix()}", "rev-parse", "HEAD"],
        cwd=REPO_ROOT,
        text=True,
    ).strip()
    modules = sorted((REPO_ROOT / "eval").glob("*.py"))
    code_hash = digest("".join(p.name + digest(p.read_text(encoding="utf-8")) for p in modules))
    lines = [
        "# Evaluation set construction report",
        "",
        "Generated by `make eval-set-report`. Do not edit by hand.",
        "",
        f"- Git SHA (base revision when run): `{sha}`",
        f"- Eval code hash: `{code_hash}`",
        f"- Config hash: `{digest(json_text(settings.model_dump(mode='json')))}`",
        f"- Corpus hash: `{manifest['corpus_hash']}`",
        f"- Frozen set hash: `{set_hash(items)}`",
        f"- Input fingerprint: `{manifest['input_fingerprint']}`",
        f"- Date (UTC): {datetime.now(UTC).date().isoformat()}",
        "- Dataset version: eval_v1; splits: dev and test; no metric tuning performed.",
        f"- Draft mode: `{manifest['draft_mode']}`; "
        f"runtime drafting model: `{manifest['draft_model']}`.",
        "- No embedding, retrieval, reranking or answer-generation models used.",
        "",
        "## Dataset versions",
        "",
        *[f"- {name}: `{version}`" for name, version in manifest["dataset_versions"].items()],
        "",
        "## Counts",
        "",
        "| Group | Candidates | Dev | Test | Total |",
        "|---|---:|---:|---:|---:|",
        *[
            f"| {group} | {manifest['candidate_counts'][group]} | {counts[group, 'dev']} | "
            f"{counts[group, 'test']} | {counts[group, 'dev'] + counts[group, 'test']} |"
            for group in GROUPS
        ],
        "",
        f"Total: {len(items)}. Answerable: {sum(item.answerable for item in items)}.",
        f"reviewed: {reviewed}/{len(items)} — waiting for human review"
        if reviewed == 0
        else f"reviewed: {reviewed}/{len(items)} — imported human decisions",
        f"Validation failures: {len(failures)}.",
        f"Distinct model-number gold products: {len(model_sections)}.",
        "",
        "## Build audit",
        "",
        "```json",
        json_text(manifest["audit"]).strip(),
        "```",
        "",
        "## Limitations and deviations",
        "",
        "- Template drafts were authored by the coding assistant; no external LLM was configured.",
        "  Optional fast-model drafting rewrites question text only and caches every response.",
        "- Look-alike model questions combine differing source attributes.",
        "  They do not represent independent product families. No synthetic facts were added.",
        "- Colloquial questions combine real Bitext prefixes with explicit FAQ context.",
        "- Cross-document questions combine same-store FAQ facts from separate topic documents.",
        "- Key-phrase absence and token support cannot prove semantic correctness.",
        "- Review flags remain human-owned; this is an unreviewed draft benchmark.",
        "- Derived text stays local under the source redistribution restrictions.",
        "",
        "## Validation failures",
        "",
        *(failures or ["None."]),
        "",
    ]
    report = "\n".join(lines)
    write_text(REPO_ROOT / "eval/reports/eval_set.md", report)
    guide = """# Evaluation set and human review

Generated by `make eval-set-report`. The construction counts and review status follow below.

## Build before retrieval

Run `make eval-build` after downloading sources and building policy documents.
It writes candidates, the frozen eval_v1 JSONL, a build manifest and a blank review CSV.
The output directory and all sampling/validation thresholds live in `configs/default.yaml`.
`make eval-validate` validates the current frozen file; `make eval-review` exports the review sheet.
`make eval-set-report` refreshes this guide and the committed construction report.
Mixed source licenses require gitignoring the generated set, cache and review sheet.
Only builder code, configuration, authored absent-topic drafts and aggregate reports are committed.

## Groups and labels

- basic_policy: source FAQ questions; gold sections come from local provenance.
  Scope prefixes distinguish Flipkart from the generic source store.
- model_number: look-alike cover models, with differing attributes extracted from source text.
  Each target/model/attribute combination is unique.
  A named distractor is not an extra gold section.
- colloquial: real Bitext utterances tagged for informal phrasing or typos, matched to FAQ intent.
  Unresolved placeholders and Bitext responses are excluded.
  Explicit FAQ context keeps the same gold.
- cross_doc: code chooses FAQ pairs from different topic documents within the same source store.
  Template or optional fast-model question drafting cannot choose or change gold labels.
- no_answer: authored draft subjects are dropped whenever their key phrase appears in any section.
  Every retained subject also needs human semantic review against the entire corpus.

## Split and validator rules

Exact normalised questions are deduplicated before sampling.
FAQ families and connected near-duplicate questions are assigned to the same split.
Fixed-seed component assignments must satisfy every group quota before questions are sampled.
The validator checks schema, counts, unique ids/questions, real gold ids, and cross_doc documents.
Every answer point needs exact numeric tokens and sufficient word overlap in a gold section.
Every gold section must support an answer point. A phrase-overlap score cannot prove entailment.
Cross-split questions are checked with normalised character similarity and token-set overlap.
The absent-topic filter is rechecked against the current corpus.
The frozen set and corpus hashes detect changed labels or changed documents.
Re-running the builder preserves human review flags and refuses changed inputs or labels.
Use a new output directory for a new version; never relabel questions to improve a score.
Tune later retrieval/gate choices on dev only. Report final quality on held-out test.

## Time-sensitive policy group

`make eval-time-sensitive-build` writes local-only `eval_v2.jsonl`. It keeps the frozen
`eval_v1` as an exact prefix and appends 24 cases per split, with 20 knowledge cases and 4 refund
cases. The index release check and frozen smoke selection continue to use v1.

- Knowledge cases use distinct dev and test phrasings for the returns and price-adjustment
  windows. Some claim an earlier purchase. All use `orders.today` and expect the current version.
- Refund cases cover returns only. Every delivered fixture uses the same default return-policy
  query built from order facts. The question text is unused, so price-adjustment cases belong
  on the knowledge path and alternate refund phrasings would repeat the same search.
- Each refund row represents one distinct date. The stored order date alone selects the gold
  version. Dev covers 2026-08-31 and 2026-09-01. Test covers 2026-08-30 and 2026-09-02.
  Each split also has an earlier and a later order.

These unreviewed cases cover two synthetic policy histories. Other policies, stores, and order
facts need separate tests. Use dev for tuning and reserve test for reporting.

`make eval-time-sensitive` writes one run record per split plus a report with Wilson confidence
intervals by split and path. It checks top-five version hits, wrong-version hits, gate passes,
and whether filters were applied. In 23a only `--filters off` is available. The refund evaluator
reads real fixture order rows and follows the production policy retrieval query for those orders.
It evaluates retrieval and the gate without an LLM or a refund decision. Use
`TIME_SENSITIVE_ARGS="--report-from <run> ..."` to rebuild the report from saved runs.

## Multipart benchmark

`make eval-multipart-build` uses the frozen `eval_v1` and the processed documents to build
local-only `eval/sets/multipart_v1.jsonl`. Seeded sampling selects distinct pairs within each
split. Each split contains 20 pairs with gold sections from two documents, 20 with one
answerable and one unanswerable part, and 10 with neither part answerable.

The template joins the source questions with `, and also ` and keeps both source IDs and labels.
Answerable parts come from the single-section basic-policy and model-number groups. Colloquial
prefixes can contain extra requests beyond their labelled FAQ, so they are excluded.
Seeded sampling puts the unanswerable part first in half of the mixed pairs in each split.
All pairs are unreviewed and share source questions with v1. Use dev to tune and test to
report multipart regression results.

## Human review workflow

Open `eval/sets/review.csv`. Compare the question, gold section text and answer points.
For no_answer, search the full corpus; the empty gold cell does not prove absence.
Write `ok` in the ok column only after confirming correctness. Leave other cells unchanged.
Import with `make eval-review-import REVIEW_CSV=eval/sets/review.csv`.
Only ok rows become reviewed; blank or other values never approve a row.
Unknown ids, duplicate ids, edited labels/text and stale source text are rejected.
Import validates the entire sheet before writing flags; it never changes questions or gold labels.
Export refuses to overwrite a sheet containing any human decision.
The coding agent must never mark the actual dataset reviewed.

## Current construction report

"""
    write_text(REPO_ROOT / "docs/EVAL_SET.md", guide + report)
    if failures:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
